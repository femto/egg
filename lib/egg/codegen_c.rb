# C code generator.
#
# Output is portable C99: no POSIX calls, no compiler extensions except
# gcc's and clang's overflow builtins, behind a check with a portable
# fallback (EGG_BUILTIN_OVERFLOW below).
# Integer arithmetic is checked (overflow and division by zero panic), and
# so are array, slice and str indexing, because Egg does not allow
# undefined behaviour to leak out of the core.
#
# Evaluation order is left to right: every call is evaluated into a
# temporary before the expression that uses it, so `f() + g()` runs f
# first whatever the C compiler does with argument order. Conditions that
# need such temporaries are lowered (`while` into `while (1) { ...; if
# (!c) break; }`, `and`/`or` into ifs) so short-circuiting is kept.
#
# Name mangling keeps Egg names away from C keywords and libc:
#   functions -> fn_<name> (methods fn_<Type>__<name>), locals v_<name>,
#   struct fields f_<name>, types ty_<name>, temporaries _t<N>;
#   runtime helpers all start with egg_, so they can never collide.
#
# Value types map to C types passed by value: a struct to a C struct, an
# array to a struct wrapping a C array (so it copies like a value), an
# error union !T to { T value; int32_t err; } (err 0 = no error). A slice
# is { const T *ptr; int64_t len; }; an inout parameter is a pointer. A
# pointer *T is a C pointer, a function type a C function pointer, an
# integer type its <stdint.h> type (usize is size_t). Structs and unions
# are tagged and declared first, so a struct may point to itself.
#
# In a debug build, each declaration and statement is preceded by a
# `#line N "file.egg"` directive (naming the module's own file), so a
# debugger built with -g shows and breaks on .egg lines instead of lines
# of the generated C.
#
# Capability values (Io, Allocator) carry no data: the capability is in
# the type, which the checker tracks. What a.concat, a.int_str and
# a.create allocate is never freed, so a str or a pointer from them is
# always valid. A Buf(T) is { T *ptr; int64_t len; } from malloc, and
# a.free(b) frees it; the ownership check (own.rb) has made sure that
# happens exactly once and that nothing uses it after.
#
# `defer` and `errdefer` emit nothing where they stand: their expression is
# emitted again at every way out of the block (its end, return, break,
# continue, and the error return of a `try`), innermost first.

module Egg
  class CodegenC
    HEADER = <<~C.freeze
      /* Generated by eggc. Do not edit. */
      #include <stdint.h>
      #include <stdbool.h>
      #include <stdio.h>
      #include <stdlib.h>
      #include <string.h>
      #include <inttypes.h>

      /* Compilers with __builtin_mul_overflow and friends (clang, gcc 5 and
         later) check overflow with the CPU's flags; others, or -DEGG_PORTABLE,
         get portable checks (slower: a multiply checks with a division).
         gcc before 10 has the builtins but not __has_builtin. */
      #if !defined(EGG_PORTABLE)
      #if defined(__has_builtin)
      #if __has_builtin(__builtin_mul_overflow)
      #define EGG_BUILTIN_OVERFLOW 1
      #endif
      #elif defined(__GNUC__) && __GNUC__ >= 5
      #define EGG_BUILTIN_OVERFLOW 1
      #endif
      #endif
    C

    STR_TYPEDEF = "typedef struct { const char *ptr; int64_t len; } egg_str;\n"
    CAP_TYPEDEFS = {
      "Io" => "typedef struct { char unused; } egg_io;\n",
      "Allocator" => "typedef struct { char unused; } egg_allocator;\n"
    }.freeze

    # Runtime helpers, emitted only when the program uses them
    # (pay only for what you use; also keeps -Wunused-function quiet).
    # Order matters: egg_panic must come first.
    HELPER_ORDER = %w[egg_panic egg_add egg_sub egg_mul egg_div egg_mod egg_neg egg_index egg_slice_check
                      egg_str_eq egg_print_i64 egg_print_bool egg_print_str egg_print_cstr
                      egg_null_deref egg_print_u64 egg_alloc egg_concat egg_int_str egg_uint_str
                      egg_fmt_float egg_print_float egg_float_str egg_cstr egg_str_from_c egg_buf_resize].freeze

    HELPERS = {
      "egg_panic" => <<~C,
        static void egg_panic(const char *msg) {
            /* abort() need not flush stdio: keep what the program printed. */
            fflush(stdout);
            fprintf(stderr, "egg panic: %s\\n", msg);
            abort();
        }
      C
      "egg_add" => <<~C,
        static int64_t egg_add(int64_t a, int64_t b) {
        #ifdef EGG_BUILTIN_OVERFLOW
            int64_t r;
            if (__builtin_add_overflow(a, b, &r)) egg_panic("integer overflow");
            return r;
        #else
            if ((b > 0 && a > INT64_MAX - b) || (b < 0 && a < INT64_MIN - b)) egg_panic("integer overflow");
            return a + b;
        #endif
        }
      C
      "egg_sub" => <<~C,
        static int64_t egg_sub(int64_t a, int64_t b) {
        #ifdef EGG_BUILTIN_OVERFLOW
            int64_t r;
            if (__builtin_sub_overflow(a, b, &r)) egg_panic("integer overflow");
            return r;
        #else
            if ((b < 0 && a > INT64_MAX + b) || (b > 0 && a < INT64_MIN + b)) egg_panic("integer overflow");
            return a - b;
        #endif
        }
      C
      "egg_mul" => <<~C,
        static int64_t egg_mul(int64_t a, int64_t b) {
        #ifdef EGG_BUILTIN_OVERFLOW
            int64_t r;
            if (__builtin_mul_overflow(a, b, &r)) egg_panic("integer overflow");
            return r;
        #else
            if (a == 0 || b == 0) return 0;
            if ((a == -1 && b == INT64_MIN) || (b == -1 && a == INT64_MIN)) egg_panic("integer overflow");
            int64_t r = (int64_t)((uint64_t)a * (uint64_t)b);
            if (r / b != a) egg_panic("integer overflow");
            return r;
        #endif
        }
      C
      "egg_div" => <<~C,
        static int64_t egg_div(int64_t a, int64_t b) {
            if (b == 0) egg_panic("division by zero");
            if (a == INT64_MIN && b == -1) egg_panic("integer overflow");
            return a / b;
        }
      C
      "egg_mod" => <<~C,
        static int64_t egg_mod(int64_t a, int64_t b) {
            if (b == 0) egg_panic("division by zero");
            if (a == INT64_MIN && b == -1) return 0;
            return a % b;
        }
      C
      "egg_neg" => <<~C,
        static int64_t egg_neg(int64_t a) {
            if (a == INT64_MIN) egg_panic("integer overflow");
            return -a;
        }
      C
      "egg_index" => <<~C,
        static int64_t egg_index(int64_t i, int64_t len) {
            if (i < 0 || i >= len) egg_panic("index out of bounds");
            return i;
        }
      C
      "egg_slice_check" => <<~C,
        static void egg_slice_check(int64_t lo, int64_t hi, int64_t len) {
            if (lo < 0 || hi < lo || hi > len) egg_panic("slice out of bounds");
        }
      C
      "egg_str_eq" => <<~C,
        static bool egg_str_eq(egg_str a, egg_str b) {
            return a.len == b.len && (a.len == 0 || memcmp(a.ptr, b.ptr, (size_t)a.len) == 0);
        }
      C
      "egg_print_i64" => <<~C,
        static void egg_print_i64(int64_t x) { printf("%" PRId64 "\\n", x); }
      C
      "egg_print_bool" => <<~C,
        static void egg_print_bool(bool x) { puts(x ? "true" : "false"); }
      C
      "egg_print_str" => <<~C,
        static void egg_print_str(egg_str s) { fwrite(s.ptr, 1, (size_t)s.len, stdout); putchar('\\n'); }
      C
      "egg_print_cstr" => <<~C,
        static void egg_print_cstr(const char *s) { puts(s); }
      C
      "egg_alloc" => <<~C,
        static char *egg_alloc(int64_t n) {
            char *p = malloc(n > 0 ? (size_t)n : 1);
            if (p == NULL) egg_panic("out of memory");
            return p;
        }
      C
      "egg_concat" => <<~C,
        static egg_str egg_concat(egg_str a, egg_str b) {
            if (a.len > INT64_MAX - b.len) egg_panic("out of memory");
            char *p = egg_alloc(a.len + b.len);
            if (a.len > 0) memcpy(p, a.ptr, (size_t)a.len);
            if (b.len > 0) memcpy(p + a.len, b.ptr, (size_t)b.len);
            return (egg_str){ p, a.len + b.len };
        }
      C
      "egg_int_str" => <<~C,
        static egg_str egg_int_str(int64_t x) {
            char buf[24];
            int n = snprintf(buf, sizeof buf, "%" PRId64, x);
            char *p = egg_alloc(n);
            memcpy(p, buf, (size_t)n);
            return (egg_str){ p, n };
        }
      C
      "egg_null_deref" => <<~C,
        static void *egg_null_deref(void) {
            egg_panic("null pointer dereference");
            return NULL;
        }
      C
      "egg_print_u64" => <<~C,
        static void egg_print_u64(uint64_t x) { printf("%" PRIu64 "\\n", x); }
      C
      "egg_uint_str" => <<~C,
        static egg_str egg_uint_str(uint64_t x) {
            char buf[24];
            int n = snprintf(buf, sizeof buf, "%" PRIu64, x);
            char *p = egg_alloc(n);
            memcpy(p, buf, (size_t)n);
            return (egg_str){ p, n };
        }
      C
      # The shortest decimal that reads back as x (with f32, as (float)x),
      # keeping ".0" on whole numbers, positional from 1e-4 to below 1e16
      # and in exponent form outside, as Python prints floats. No math.h:
      # it would claim names (sqrt, sin) an extern fn may want.
      "egg_fmt_float" => <<~C,
        static void egg_fmt_float(char *buf, double x, bool f32) {
            if (x != x) { strcpy(buf, "nan"); return; }
            if (x - x != x - x) { strcpy(buf, x > 0 ? "inf" : "-inf"); return; }
            int p = 1;
            for (; p < (f32 ? 9 : 17); p++) {
                snprintf(buf, 40, "%.*e", p - 1, x);
                if (f32 ? strtof(buf, NULL) == (float)x : strtod(buf, NULL) == x) break;
            }
            snprintf(buf, 40, "%.*e", p - 1, x);
            int exp = atoi(strchr(buf, 'e') + 1);
            if (exp >= -4 && exp < 16) snprintf(buf, 40, "%.*f", p - 1 - exp < 1 ? 1 : p - 1 - exp, x);
        }
      C
      "egg_print_float" => <<~C,
        static void egg_print_float(double x, bool f32) {
            char buf[40];
            egg_fmt_float(buf, x, f32);
            puts(buf);
        }
      C
      "egg_float_str" => <<~C,
        static egg_str egg_float_str(double x, bool f32) {
            char buf[40];
            egg_fmt_float(buf, x, f32);
            int64_t n = (int64_t)strlen(buf);
            char *p = egg_alloc(n);
            memcpy(p, buf, (size_t)n);
            return (egg_str){ p, n };
        }
      C
      # s for C: its bytes and a 0 (C reads up to the first 0 byte).
      "egg_cstr" => <<~C,
        static uint8_t *egg_cstr(egg_str s) {
            if (s.len == INT64_MAX) egg_panic("out of memory");
            char *p = egg_alloc(s.len + 1);
            if (s.len > 0) memcpy(p, s.ptr, (size_t)s.len);
            p[s.len] = 0;
            return (uint8_t *)p;
        }
      C
      # The 0-terminated bytes at p, copied into a str.
      "egg_str_from_c" => <<~C,
        static egg_str egg_str_from_c(const uint8_t *p) {
            if (p == NULL) egg_panic("null pointer dereference");
            int64_t n = (int64_t)strlen((const char *)p);
            char *q = egg_alloc(n);
            if (n > 0) memcpy(q, p, (size_t)n);
            return (egg_str){ q, n };
        }
      C
      # p (NULL for a new buffer) resized to n elements of size bytes.
      "egg_buf_resize" => <<~C
        static void *egg_buf_resize(void *p, int64_t n, size_t size) {
            if (n < 0) egg_panic("negative buffer length");
            if ((uint64_t)n > SIZE_MAX / size) egg_panic("out of memory");
            void *q = realloc(p, n > 0 ? (size_t)n * size : 1);
            if (q == NULL) egg_panic("out of memory");
            return q;
        }
      C
    }.freeze

    # Helpers that call others.
    HELPER_DEPS = { "egg_concat" => ["egg_alloc"], "egg_int_str" => ["egg_alloc"], "egg_uint_str" => ["egg_alloc"],
                    "egg_print_float" => ["egg_fmt_float"], "egg_float_str" => %w[egg_alloc egg_fmt_float],
                    "egg_cstr" => ["egg_alloc"], "egg_str_from_c" => ["egg_alloc"] }.freeze
    # Helpers that never panic, so need no egg_panic.
    NO_PANIC = %w[egg_str_eq egg_fmt_float].freeze
    FLOAT_C = { "f32" => "float", "f64" => "double" }.freeze

    ARITH_FN = { "+" => "egg_add", "-" => "egg_sub", "*" => "egg_mul", "/" => "egg_div", "%" => "egg_mod" }.freeze
    ARITH_NAME = { "+" => "add", "-" => "sub", "*" => "mul", "/" => "div", "%" => "mod" }.freeze

    # Integer types: [C type, minimum, maximum]. i64 uses the helpers above;
    # the others get theirs generated (int_helper) when used.
    INT_C = {
      "i8" => %w[int8_t INT8_MIN INT8_MAX], "i16" => %w[int16_t INT16_MIN INT16_MAX],
      "i32" => %w[int32_t INT32_MIN INT32_MAX], "i64" => %w[int64_t INT64_MIN INT64_MAX],
      "u8" => %w[uint8_t 0 UINT8_MAX], "u16" => %w[uint16_t 0 UINT16_MAX],
      "u32" => %w[uint32_t 0 UINT32_MAX], "u64" => %w[uint64_t 0 UINT64_MAX],
      "usize" => %w[size_t 0 SIZE_MAX]
    }.freeze

    # debug_path: the root file's absolute path for a debug build, or nil
    def initialize(program, checker, debug_path = nil)
      @program = program
      @checker = checker
      @types = checker.types
      @debug = !debug_path.nil?
      @root_path = debug_path
      @line_file = nil
      @need_cap = {}
      @int_helpers = {} # name -> C text, generated in use order
      @drops = {}       # owned type -> its egg_drop_ function's name
      @out = +""
      @indent = 0
      @locals = []
      @used = {}
      @enum_names = {}
      @need_str = false
      @tmp = 0
      @sig = nil
      @defers = []      # per open block: its Defer statements so far
      @loop_marks = []  # per open loop: how many blocks were open outside it
    end

    def generate
      # Function bodies first, so we know which helpers and tables they use.
      @checker.concrete.each { |sig| gen_func(sig) }
      gen_entry
      body = @out

      @out = +""
      emit_types
      types = @out

      out = HEADER.dup
      out << "\n"
      out << STR_TYPEDEF << "\n" if @need_str
      CAP_TYPEDEFS.each { |t, text| out << text << "\n" if @need_cap[t] }
      out << types
      HELPER_ORDER.each do |name|
        next unless @used[name]
        out << HELPERS[name] << "\n"
      end
      @int_helpers.each_value { |text| out << text << "\n" }
      @enum_names.each_key do |canon|
        info = @types[canon]
        names = info.members.map { |m| c_string(m) }.join(", ")
        out << "static const char *const #{info.c_name}_names[] = { #{names} };\n"
      end
      if @checker.main_sig.ret == "!void"
        names = ["\"\""] + @checker.error_names.map { |n| c_string(n) }
        out << "static const char *const egg_error_names[] = { #{names.join(', ')} };\n"
      end
      if @need_error_names
        # @errorName(e): error ids index this table
        strs = ["{ \"\", 0 }"] + @checker.error_names.map { |n| "{ #{c_string(n)}, #{n.bytesize} }" }
        out << "static const egg_str egg_error_strs[] = { #{strs.join(', ')} };\n"
      end
      out << "\n"
      # One prototype per C function, however many files declare it.
      @checker.externs.uniq(&:c_name).each { |sig| out << extern_prototype(sig) << ";\n" }
      @checker.concrete.each { |sig| out << signature(sig) << ";\n" }
      out << "\n"
      # After the prototypes: an owned struct's drop calls its deinit.
      emit_drops(out)
      out << body
      out
    end

    private

    # Deep free of an owned value: a buffer's elements, then the buffer; a
    # struct's owned fields, last declared first; an array's elements; an
    # owned struct, by its deinit. Returns the function.
    def drop(t)
      return @drops[t] if @drops.key?(t)
      @drops[t] = "egg_drop_#{@types[t].c_name}"
      info = @types[t]
      case info.kind
      when :buf, :array then drop(info.elem) if @checker.owned?(info.elem)
      when :struct then info.fields.each { |_, ft, _| drop(ft) if @checker.owned?(ft) } if info.deinit.nil?
      end
      @drops[t]
    end

    def emit_drops(out)
      return if @drops.empty?
      @drops.each { |t, name| out << "static void #{name}(#{c_type(t)} v);\n" }
      @drops.each do |t, name|
        info = @types[t]
        body = case info.kind
               when :buf
                 elem = @checker.owned?(info.elem) ? "    for (int64_t i = 0; i < v.len; i++) #{drop(info.elem)}(v.ptr[i]);\n" : ""
                 "#{elem}    free(v.ptr);\n"
               when :array
                 "    for (int64_t i = 0; i < #{info.len}; i++) #{drop(info.elem)}(v.a[i]);\n"
               when :struct
                 if !info.deinit.nil?
                   # Its deinit ends it, fields and all.
                   a = info.deinit.params.length == 2 ? ", (egg_allocator){ 0 }" : ""
                   "    #{info.deinit.c_name}(v#{a});\n"
                 else
                   # Fields last declared first, as they may depend on earlier ones.
                   info.fields.select { |_, ft, _| @checker.owned?(ft) }.reverse.map { |f, ft, _| "    #{drop(ft)}(v.f_#{f});\n" }.join
                 end
               end
        out << "static void #{name}(#{c_type(t)} v) {\n#{body}}\n"
      end
      out << "\n"
    end

    # Buf(T).empty: no elements, nothing on the heap.
    def empty_buf(t)
      "((#{c_type(t)}){ .ptr = NULL, .len = 0 })"
    end

    # Record a helper call; every checked helper also needs egg_panic.
    # The checked helper for `op` ("+", "-", ..., "neg") on integer type t.
    def int_op(op, t)
      return(op == "neg" ? helper("egg_neg") : helper(ARITH_FN[op])) if t == "i64"
      kind = op == "neg" ? "neg" : ARITH_NAME[op]
      name = "egg_#{kind}_#{t}"
      unless @int_helpers.key?(name)
        helper("egg_panic")
        @int_helpers[name] = int_helper(kind, t, name)
      end
      name
    end

    # C for one checked operation on a non-i64 integer type. Narrow types
    # compute in 64 bits and check the range; u64 and usize, which cannot
    # be widened, check before computing.
    def int_helper(kind, t, name)
      ct, min, max = INT_C[t]
      signed = t.start_with?("i")
      wide = %w[u64 usize].include?(t)
      ovf = 'egg_panic("integer overflow")'
      body =
        case kind
        when "add", "sub", "mul"
          op = { "add" => "+", "sub" => "-", "mul" => "*" }[kind]
          if signed
            "int64_t r = (int64_t)a #{op} (int64_t)b;\n    if (r < #{min} || r > #{max}) #{ovf};\n    return (#{ct})r;"
          elsif kind == "sub"
            "if (b > a) #{ovf};\n    return (#{ct})(a - b);"
          elsif wide
            portable = kind == "add" ? "if (a > #{max} - b) #{ovf};\n    return a + b;" : "if (a != 0 && b > #{max} / a) #{ovf};\n    return a * b;"
            "#ifdef EGG_BUILTIN_OVERFLOW\n    #{ct} r;\n    if (__builtin_#{kind}_overflow(a, b, &r)) #{ovf};\n    return r;\n" \
              "#else\n    #{portable}\n#endif"
          else
            "uint64_t r = (uint64_t)a #{op} (uint64_t)b;\n    if (r > #{max}) #{ovf};\n    return (#{ct})r;"
          end
        when "div"
          check = signed ? "\n    if (a == #{min} && b == -1) #{ovf};" : ""
          "if (b == 0) egg_panic(\"division by zero\");#{check}\n    return (#{ct})(a / b);"
        when "mod"
          check = signed ? "\n    if (b == -1) return 0;" : ""
          "if (b == 0) egg_panic(\"division by zero\");#{check}\n    return (#{ct})(a % b);"
        when "neg"
          return "static #{ct} #{name}(#{ct} a) {\n    if (a == #{min}) #{ovf};\n    return (#{ct})-a;\n}\n"
        end
      "static #{ct} #{name}(#{ct} a, #{ct} b) {\n    #{body}\n}\n"
    end

    # x of integer type `from` as integer type `to`, checked: the value is
    # carried in 64 bits (signed or not, as `from` is) and must survive the
    # round trip through `to` (comparisons with constants would be always
    # true for some pairs, which -Wtype-limits rejects).
    def as_conv(from, to, code)
      ct, _, max = INT_C[to]
      src = from.start_with?("i") ? "s" : "u"
      wide = src == "s" ? "int64_t" : "uint64_t"
      name = "egg_as_#{to}_#{src}"
      unless @int_helpers.key?(name)
        helper("egg_panic")
        test =
          if src == "s" && to.start_with?("i") then "(int64_t)r != x"
          elsif src == "s" then "x < 0 || (uint64_t)r != (uint64_t)x"
          elsif to.start_with?("i") then "x > (uint64_t)#{max}"
          else "(uint64_t)r != x"
          end
        @int_helpers[name] = "static #{ct} #{name}(#{wide} x) {\n    #{ct} r = (#{ct})x;\n" \
                             "    if (#{test}) egg_panic(\"integer cast out of range\");\n    return r;\n}\n"
      end
      "#{name}((#{wide})#{code})"
    end

    # x of number type `from` as number type `to`, when either is a float.
    # To an integer type it is checked: x truncated toward zero must fit
    # (C leaves anything else undefined), and nan and inf never do.
    def float_conv(from, to, code)
      return "((#{FLOAT_C[to]})#{code})" if FLOAT_C.key?(to)
      ct = INT_C[to][0]
      name = "egg_as_#{to}_f"
      unless @int_helpers.key?(name)
        helper("egg_panic")
        bits = to == "usize" ? 64 : to[1..].to_i
        # The open range of x around the type: (lo - 1, hi + 1). For 64
        # bits lo - 1 is no double, but nothing lies between it and lo.
        lo, hi = to.start_with?("i") ? [-(2**(bits - 1)), 2**(bits - 1)] : [0, 2**bits]
        test = bits == 64 && to.start_with?("i") ? "x >= #{lo}.0" : "x > #{lo - 1}.0"
        @int_helpers[name] = "static #{ct} #{name}(double x) {\n" \
                             "    if (!(#{test} && x < #{hi}.0)) egg_panic(\"float cast out of range\");\n" \
                             "    return (#{ct})x;\n}\n"
      end
      "#{name}((double)#{code})"
    end

    # A float literal (its text as written) of type t.
    def float_lit(text, t)
      t == "f32" ? "#{text}f" : text
    end

    # An integer literal of type t (which may be a float type: 2 as an f64).
    def int_lit(value, t)
      return float_lit("#{value}.0", t) if FLOAT_C.key?(t)
      return(value == -9_223_372_036_854_775_808 ? "INT64_MIN" : "INT64_C(#{value})") if t == "i64" || t.nil?
      ct, min, = INT_C[t]
      return "UINT64_C(#{value})" if t == "u64"
      # usize is as wide as a pointer: above 32 bits, check it fits size_t
      # (a no-op on 64-bit targets, a panic instead of truncation on others).
      return as_conv("u64", "usize", "UINT64_C(#{value})") if t == "usize" && value > 4_294_967_295
      # The minimum (-128) is not writable as a C literal of its type.
      return "((#{ct})#{min})" if value == TypeChecker::INT_RANGE[t][0] && value.negative?
      "((#{ct})#{value})"
    end

    def helper(name)
      @used[name] = true
      @used["egg_panic"] = true unless name.start_with?("egg_print") || NO_PANIC.include?(name)
      @need_str = true if %w[egg_str_eq egg_print_str egg_concat egg_int_str egg_uint_str egg_float_str egg_cstr egg_str_from_c].include?(name)
      (HELPER_DEPS[name] || []).each { |d| helper(d) }
      name
    end

    # The quoted file name for #line marks in code of module `prefix`.
    def file_of(prefix)
      return nil unless @debug
      path = @checker.modules[prefix || ""].path || @root_path
      c_string(path)
    end

    # ---- types --------------------------------------------------------

    def c_type(t)
      case t
      when "i64" then "int64_t"
      when "bool" then "bool"
      when "void" then "void"
      when "anyerror" then "int32_t"
      when "str"
        @need_str = true
        "egg_str"
      when "Io"
        @need_cap[t] = true
        "egg_io"
      when "Allocator"
        @need_cap[t] = true
        "egg_allocator"
      when *INT_C.keys then INT_C[t][0]
      when *FLOAT_C.keys then FLOAT_C[t]
      else
        info = @types[t]
        return "#{c_type(info.inner)} *" if info&.kind == :ptr
        raise "codegen: unknown type #{t}" if info.nil?
        info.c_name
      end
    end

    # Typedefs in dependency order: a struct after the types it holds by
    # value. Slices hold only pointers and come last.
    # Structs and unions are tagged and declared up front, so a pointer
    # field can name a struct that is defined later (or itself).
    def emit_types
      @checker.type_order.each do |c|
        info = @types[c]
        @out << "typedef struct #{info.c_name} #{info.c_name};\n" if %i[struct union].include?(info.kind)
      end
      @out << "\n" if @checker.type_order.any? { |c| %i[struct union].include?(@types[c].kind) }
      done = {}
      @checker.type_order.each { |c| emit_type(c, done) unless @types[c].kind == :slice }
      @checker.type_order.each { |c| emit_type(c, done) if @types[c].kind == :slice }
    end

    def emit_type(canon, done)
      info = @types[canon]
      return if info.nil? || info.kind == :prim || done[canon]
      done[canon] = true
      # Marks name the declaring module's file; emitting a field's type
      # (maybe from another module) first must not change that. Arrays,
      # error unions and slices have no module and keep the enclosing one.
      saved = @line_file
      @line_file = file_of(info.mod) unless info.mod.nil?
      emit_type_body(canon, info, done)
      @line_file = saved
    end

    def emit_type_body(canon, info, done)
      case info.kind
      when :enum
        mark(info.line)
        @out << "typedef int32_t #{info.c_name};\n"
        (info.member_lines || []).uniq.each { |l| mark(l) unless l == info.line }
        @out << "\n" unless (info.member_lines || []).uniq == [info.line]
      when :struct
        info.fields.each { |_, t, _| emit_type(t, done) }
        mark(info.fn_line) unless info.fn_line.nil?
        @out << "/* #{canon} */\n" unless info.fn_line.nil?
        mark(info.return_line || info.line)
        @out << "struct #{info.c_name} {\n"
        if info.fields.empty?
          @out << "    char unused;\n"
        else
          info.fields.each do |name, t, l|
            mark(l)
            @out << "    #{c_type(t)} f_#{name};\n"
          end
        end
        @out << "};\n\n"
      when :union
        # { tag, union of payloads }; tag is the member's index.
        info.fields.each { |_, t, _| emit_type(t, done) unless t == "void" }
        mark(info.line)
        payloads = info.fields.reject { |_, t, _| t == "void" }
        @out << "struct #{info.c_name} {\n    int32_t tag;\n"
        unless payloads.empty?
          @out << "    union {\n"
          payloads.each { |n, t, _| @out << "        #{c_type(t)} m_#{n};\n" }
          @out << "    } u;\n"
        end
        info.fields.each { |_, _, l| mark(l) unless l == info.line }
        @out << "};\n\n"
      when :array
        emit_type(info.elem, done)
        @out << "typedef struct { #{c_type(info.elem)} a[#{info.len}]; } #{info.c_name};\n"
      when :err
        emit_type(info.inner, done)
        if info.inner == "void"
          @out << "typedef struct { int32_t err; } #{info.c_name};\n"
        else
          @out << "typedef struct { #{c_type(info.inner)} value; int32_t err; } #{info.c_name};\n"
        end
      when :opt
        emit_type(info.inner, done)
        @out << "typedef struct { #{c_type(info.inner)} value; bool has; } #{info.c_name};\n"
      when :slice
        emit_type(info.elem, done)
        @out << "typedef struct { const #{c_type(info.elem)} *ptr; int64_t len; } #{info.c_name};\n"
      when :buf
        emit_type(info.elem, done)
        @out << "typedef struct { #{c_type(info.elem)} *ptr; int64_t len; } #{info.c_name};\n"
      when :ptr
        # A struct or union target is declared up front; others are needed.
        emit_type(info.inner, done) unless %i[struct union].include?(@types[info.inner]&.kind)
      when :fn
        (info.fields + [info.inner]).each { |t| emit_type(t, done) unless %i[struct union].include?(@types[t]&.kind) }
        params = info.fields.empty? ? "void" : info.fields.map { |t| c_type(t) }.join(", ")
        @out << "typedef #{c_type(info.inner)} (*#{info.c_name})(#{params});\n"
      end
    end

    # ---- functions ----------------------------------------------------

    def signature(sig)
      runtime = sig.func.params.reject { |p| p.mode == "comptime" }
      params = runtime.each_with_index.map do |p, i|
        t, mode = sig.params[i]
        mode == "inout" ? "#{c_type(t)} *v_#{p.name}" : "#{c_type(t)} v_#{p.name}"
      end
      params_text = params.empty? ? "void" : params.join(", ")
      # Not static: an unused function is not an error in Egg, and external
      # linkage keeps C's -Wunused-function quiet. Names are prefixed, so
      # they cannot clash with libc.
      "#{c_type(sig.ret)} #{sig.c_name}(#{params_text})"
    end

    # extern fn: the C function, declared with the exact C types.
    def extern_prototype(sig)
      params = sig.params.empty? ? "void" : sig.params.map { |t, _| c_type(t) }.join(", ")
      "#{c_type(sig.ret)} #{sig.c_name}(#{params})"
    end

    def gen_func(sig)
      @sig = sig
      @line_file = file_of(sig.func.mod)
      @tmp = 0
      @locals = [{}]
      runtime = sig.func.params.reject { |p| p.mode == "comptime" }
      runtime.each_with_index do |p, i|
        t, mode = sig.params[i]
        @locals.last[p.name] = [t, mode == "inout"]
      end
      mark(sig.func.line)
      @out << signature(sig) << " {\n"
      @indent = 1
      (sig.unused || []).each { |name| line("(void)v_#{name};") }
      @defers = [[]]
      @loop_marks = []
      sig.func.body.stmts.each { |s| gen_stmt(s) }
      emit_defers(0, false) unless ends_block?(sig.func.body.stmts)
      line("return (#{c_type('!void')}){ 0 };") if sig.ret == "!void"
      @out << "}\n\n"
      nil
    end

    # main's capability parameters are made here: the runtime is where
    # capabilities come from.
    def gen_entry
      main = @checker.main_sig
      @line_file = file_of("")
      mark(main.func.line)
      @out << "int main(void) {\n"
      args = main.params.map { |t, _| "(#{c_type(t)}){ 0 }" }.join(", ")
      case main.ret
      when "i64"
        @out << "    return (int)#{main.c_name}(#{args});\n"
      when "!void"
        @out << "    #{c_type('!void')} r = #{main.c_name}(#{args});\n"
        @out << "    if (r.err) {\n"
        @out << "        fprintf(stderr, \"error: %s\\n\", egg_error_names[r.err]);\n"
        @out << "        return 1;\n"
        @out << "    }\n"
        @out << "    return 0;\n"
      else
        @out << "    #{main.c_name}(#{args});\n    return 0;\n"
      end
      @out << "}\n"
      nil
    end

    def gen_block(block)
      @locals << {}
      @defers << []
      @indent += 1
      block.stmts.each { |s| gen_stmt(s) }
      emit_defers(@defers.length - 1, false) unless ends_block?(block.stmts)
      @indent -= 1
      @defers.pop
      @locals.pop
      nil
    end

    # Does the block end by jumping away (so its end is never reached)?
    def ends_block?(stmts)
      [Return, Break, Continue].any? { |k| stmts.last.is_a?(k) }
    end

    def defers?
      @defers.any? { |f| !f.empty? }
    end

    # Emit the deferred expressions of the blocks from the innermost one
    # down to index `down`, last deferred first. error: whether errdefers
    # run (true, false, or a C condition tested at run time).
    def emit_defers(down, error)
      emitted = false
      i = @defers.length - 1
      while i >= down
        @defers[i].reverse_each do |d|
          next if d.err && error == false
          mark(d.line)
          code, pre = capture { expr(d.expr) }
          if d.err && error != true
            line("if (#{error}) {")
            @indent += 1
            emit_raw(pre.gsub(/^/, "    "))
            line("#{code};") unless code.empty?
            @indent -= 1
            line("}")
          else
            emit_raw(pre)
            line("#{code};") unless code.empty?
          end
          emitted = true
        end
        i -= 1
      end
      emitted
    end

    def line(text)
      @out << ("    " * @indent) << text << "\n"
      nil
    end

    # Attribute the C that follows to an .egg line (debug builds only).
    def mark(src_line)
      return if @line_file.nil? || src_line.nil?
      @out << "#line #{src_line} #{@line_file}\n"
      nil
    end

    def c_string(text)
      out = +"\""
      text.each_byte do |b|
        if b == 34 || b == 92
          out << "\\" << b.chr
        elsif b >= 32 && b < 127 && b != 63 # '?' escaped against trigraphs
          out << b.chr
        else
          out << format("\\%03o", b)
        end
      end
      out << "\""
    end

    def tmp
      @tmp += 1
      "_t#{@tmp}"
    end

    # Run the block with output going to a separate buffer; returns
    # [block's value, the lines it emitted].
    def capture
      saved = @out
      @out = +""
      value = yield
      [value, @out]
    ensure
      @out = saved
    end

    def emit_raw(text)
      @out << text
    end

    def declare_local(name, ty)
      @locals.last[name] = [ty, false]
    end

    # ---- statements ---------------------------------------------------

    def gen_stmt(stmt)
      mark(stmt.line)
      case stmt
      in VarDecl[name:, value:, ty:]
        code = coerce(expr(value), value.ty, ty)
        declare_local(name, ty)
        line("#{c_type(ty)} v_#{name} = #{code};")
      in Assign[name:, value:, target:]
        if target.nil?
          code = coerce(expr(value), value.ty, local(name)[0])
          line("#{var_ref(name)} = #{code};")
        else
          code = coerce(expr(value), value.ty, target.ty)
          line("#{lvalue(target)} = #{code};")
        end
      in If
        gen_if(stmt)
      in While[cond:, body:]
        @loop_marks << @defers.length
        c, pre = capture { cond(cond) }
        if pre.empty?
          line("while (#{c}) {")
        else
          line("while (1) {")
          @indent += 1
          c, pre = capture { cond(cond) }
          emit_raw(pre)
          line("if (!(#{c})) break;")
          @indent -= 1
        end
        gen_block(body)
        line("}")
        @loop_marks.pop
      in For
        gen_for(stmt)
      in Switch
        gen_switch(stmt)
      in Break
        mark(stmt.line) if emit_defers(@loop_marks.last, false)
        line("break;")
      in Continue
        mark(stmt.line) if emit_defers(@loop_marks.last, false)
        line("continue;")
      in Return[value:]
        gen_return(value, stmt.line)
      in Defer
        @defers.last << stmt
      in ExprStmt[expr: e]
        code = expr(e)
        line("#{code};") unless code.empty?
      else
        raise "codegen: unhandled statement #{stmt.class}"
      end
    end

    def gen_return(value, src_line)
      ret = @sig.ret
      if value.nil?
        mark(src_line) if emit_defers(0, false)
        line(ret == "!void" ? "return (#{c_type(ret)}){ 0 };" : "return;")
      elsif !defers?
        line("return #{coerce(expr(value), value.ty, ret)};")
      else
        # The value first, then the defers, which may change what it came from.
        r = hoist(coerce(expr(value), value.ty, ret), ret)
        error = false
        error = value.is_a?(ErrorLit) || value.ty == "anyerror" ? true : (value.ty.start_with?("!") ? "#{r}.err" : false) if ret.start_with?("!")
        mark(src_line) if emit_defers(0, error)
        line("return #{r};")
      end
    end

    # if / else if / else chains become one flat C chain, unless an else-if
    # condition needs temporaries: then it nests inside the else.
    def gen_if(stmt)
      c = cond(stmt.cond)
      line("if (#{c}) {")
      gen_block(stmt.then_body)
      tail = stmt.else_body
      closers = 0
      while tail.is_a?(If)
        tc, pre = capture { cond(tail.cond) }
        if pre.empty? && @line_file.nil?
          line("} else if (#{tc}) {")
        elsif pre.empty?
          # A directive needs its own line, so split "} else if" around it.
          line("}")
          mark(tail.line)
          line("else if (#{tc}) {")
        else
          line("} else {")
          @indent += 1
          closers += 1
          mark(tail.line)
          tc, pre = capture { cond(tail.cond) }
          emit_raw(pre)
          line("if (#{tc}) {")
        end
        gen_block(tail.then_body)
        tail = tail.else_body
      end
      unless tail.nil?
        line("} else {")
        gen_block(tail)
      end
      line("}")
      closers.times do
        @indent -= 1
        line("}")
      end
    end

    def gen_for(stmt)
      it = stmt.iter
      t = it.ty
      idx = tmp
      if t == "str"
        s = tmp
        line("egg_str #{s} = #{expr(it)};")
        @need_str = true
        len = "#{s}.len"
        item = "(int64_t)(unsigned char)#{s}.ptr[#{idx}]"
        elem = "i64"
      else
        info = @types[t]
        elem = info.elem
        ptr = tmp
        if info.kind == :array
          base = place?(it) ? lvalue(it) : hoist(expr(it), t)
          line("const #{c_type(elem)} *#{ptr} = #{base}.a;")
          len = "INT64_C(#{info.len})"
        else
          s = hoist(expr(it), t)
          line("const #{c_type(elem)} *#{ptr} = #{s}.ptr;")
          len = "#{s}.len"
        end
        item = "#{ptr}[#{idx}]"
      end
      line("for (int64_t #{idx} = 0; #{idx} < #{len}; #{idx}++) {")
      @loop_marks << @defers.length
      @locals << {}
      @indent += 1
      unless stmt.var == "_"
        declare_local(stmt.var, elem)
        line("const #{c_type(elem)} v_#{stmt.var} = #{item};")
      end
      unless stmt.index_var.nil? || stmt.index_var == "_"
        declare_local(stmt.index_var, "i64")
        line("const int64_t v_#{stmt.index_var} = #{idx};")
      end
      @indent -= 1
      gen_block(stmt.body)
      @locals.pop
      @loop_marks.pop
      line("}")
    end

    # switch becomes an if chain over the tag (not a C switch, so that a
    # `break` in an arm still leaves the enclosing loop).
    def gen_switch(stmt)
      subject = stmt.subject
      t = subject.ty
      info = @types[t]
      base = place?(subject) ? lvalue(subject) : hoist(expr(subject), t)
      tag = info&.kind == :union ? "#{base}.tag" : base
      # The checker proved the arms exhaustive, so the last arm needs no
      # test; C then also sees that every path returns.
      last = stmt.arms.length - 1
      stmt.arms.each_with_index do |arm, i|
        if arm.names.nil? || i == last
          if i.zero?
            mark(arm.line)
            line("{")
          else
            line("}")
            mark(arm.line)
            line("else {")
          end
        else
          test = arm.names.map do |n|
            idx = if t == "anyerror" then @checker.error_names.index(n.delete_prefix("error.")) + 1
                  elsif info.kind == :union then info.fields.index { |m, _| m == n }
                  else info.members.index(n)
                  end
            "#{tag} == #{idx}"
          end.join(" || ")
          if i.zero?
            mark(arm.line)
            line("if (#{test}) {")
          else
            line("}")
            mark(arm.line)
            line("else if (#{test}) {")
          end
        end
        @locals << {}
        unless arm.capture.nil? || arm.capture == "_"
          payload = info.fields.find { |m, _| m == arm.names[0] }[1]
          declare_local(arm.capture, payload)
          line("    const #{c_type(payload)} v_#{arm.capture} = #{base}.u.m_#{arm.names[0]};")
        end
        gen_block(arm.body)
        @locals.pop
      end
      line("}")
    end

    # ---- expressions --------------------------------------------------

    # A condition already sits inside if (...) / while (...), so drop the
    # outer parentheses that expr adds (clang warns on `if ((a == b))`).
    def cond(e)
      text = expr(e)
      if e.is_a?(Binary) && !ARITH_FN.key?(e.op) && text.start_with?("(") && text.end_with?(")")
        text[1...-1]
      else
        text
      end
    end

    # Evaluate code once into a temporary of type t; returns its name.
    def hoist(code, t)
      name = tmp
      line("#{c_type(t)} #{name} = #{code};")
      name
    end

    # Wrap a value for a !T slot: T -> { value, 0 }, error.X -> { .err = X }.
    def coerce(code, from, to)
      return code if to.nil? || from == to
      return "((#{c_type(to)}){ .value = #{code}, .has = true })" if to.start_with?("?")
      return code unless to.start_with?("!")
      if from == "anyerror"
        "((#{c_type(to)}){ .err = #{code} })"
      else
        "((#{c_type(to)}){ .value = #{code}, .err = 0 })"
      end
    end

    def expr(e)
      case e
      in IntLit[value:]
        int_lit(value, e.ty)
      in FloatLit[text:]
        float_lit(text, e.ty)
      in BoolLit[value:]
        value ? "true" : "false"
      in StrLit[value:]
        @need_str = true
        "((egg_str){ #{c_string(value)}, #{value.bytesize} })"
      in Var[info: { fn_ref: String => c_name }]
        c_name
      in Var[name:]
        var_ref(name)
      in Unary[op:, operand:, info: { neg_lit: true }]
        # As a float, -0 keeps its sign: negate the literal, do not fold it.
        FLOAT_C.key?(e.ty) ? "(-#{int_lit(operand.value, e.ty)})" : int_lit(-operand.value, e.ty)
      in Unary[op:, operand:]
        if op != "-" then "(!#{expr(operand)})"
        elsif FLOAT_C.key?(e.ty) then "(-#{expr(operand)})"
        else "#{int_op('neg', e.ty)}(#{expr(operand)})"
        end
      in Binary[op:, lhs:, rhs:]
        binary(op, lhs, rhs)
      in Call[name:, info: { indirect: true } => info]
        call(var_ref(name), info[:args], info[:params], [], e.ty)
      in Call[info:]
        call(info[:c_name], info[:args], info[:params], [], e.ty)
      in MethodCall[obj:, info: { cap_method: String => m }]
        cap_call(m, obj, e.args, e.ty)
      in MethodCall[obj:, name:, info: { field_call: true } => info]
        call("#{struct_value(obj)}.f_#{name}", info[:args], info[:params], [], e.ty)
      in MethodCall[obj:, info:]
        recv = []
        unless info[:static]
          recv << (info[:self_inout] ? "&#{lvalue(obj)}" : expr(obj))
        end
        call(info[:c_name], info[:args], info[:params], recv, e.ty)
      in Builtin[name:, args:]
        builtin(e, name, args)
      in Field[obj:, name:, info:]
        return empty_buf(e.ty) if info[:buf_empty]
        return "((#{c_type(e.ty)}){ .tag = #{info[:union_tag]} })" unless info[:union_tag].nil?
        return "((#{c_type(e.ty)})#{info[:enum_index]})" unless info[:enum_index].nil?
        "#{struct_value(obj)}.f_#{name}"
      in Index[obj:, index:]
        index_expr(obj, index, e.info[:len])
      in SliceExpr
        slice_expr(e)
      in StructLit[fields:, info: { union_tag: Integer => tag, member: String => member }]
        value = fields[0][1]
        payload = @types[e.ty].fields[tag][1]
        "((#{c_type(e.ty)}){ .tag = #{tag}, .u.m_#{member} = #{coerce(expr(value), value.ty, payload)} })"
      in StructLit[fields:]
        info = @types[e.ty]
        inits = fields.map do |fname, value, _, _|
          ftype = info.fields.find { |n, _| n == fname }[1]
          ".f_#{fname} = #{coerce(expr(value), value.ty, ftype)}"
        end
        inits = ["0"] if inits.empty?
        "((#{c_type(e.ty)}){ #{inits.join(', ')} })"
      in ArrayLit[items:]
        elem = @types[e.ty].elem
        vals = items.map { |i| coerce(expr(i), i.ty, elem) }
        "((#{c_type(e.ty)}){ { #{vals.join(', ')} } })"
      in EnumLit[info: { buf_empty: true }]
        empty_buf(e.ty)
      in EnumLit[info: { union_tag: Integer => tag }]
        "((#{c_type(e.ty)}){ .tag = #{tag} })"
      in EnumLit[info:]
        "((#{c_type(e.ty)})#{info[:enum_index]})"
      in ErrorLit[info:]
        info[:error_id].to_s
      in NullLit
        @types[e.ty].kind == :opt ? "((#{c_type(e.ty)}){ .has = false })" : "((#{c_type(e.ty)})0)"
      in AddrOf[expr: place]
        "(&#{lvalue(place)})"
      in Deref
        lvalue(e)
      in Try[expr: inner]
        r = hoist(expr(inner), inner.ty)
        if defers?
          line("if (#{r}.err) {")
          @indent += 1
          emit_defers(0, true)
          line("return (#{c_type(@sig.ret)}){ .err = #{r}.err };")
          @indent -= 1
          line("}")
        else
          line("if (#{r}.err) return (#{c_type(@sig.ret)}){ .err = #{r}.err };")
        end
        e.ty == "void" ? "" : "#{r}.value"
      in Orelse[expr: inner, fallback:]
        r = hoist(expr(inner), inner.ty)
        out = tmp
        line("#{c_type(e.ty)} #{out};")
        line("if (!#{r}.has) {")
        @indent += 1
        case fallback
        in Return | Break | Continue then gen_stmt(fallback)
        in Block then gen_block(fallback)
        else line("#{out} = #{coerce(expr(fallback), fallback.ty, e.ty)};")
        end
        @indent -= 1
        line("} else {")
        line("    #{out} = #{r}.value;")
        line("}")
        out
      in Catch[expr: inner, fallback:, capture:]
        r = hoist(expr(inner), inner.ty)
        out = nil
        unless e.ty == "void"
          out = tmp
          line("#{c_type(e.ty)} #{out};")
        end
        line("if (#{r}.err) {")
        @indent += 1
        @locals << {}
        unless capture.nil? || capture[0] == "_"
          declare_local(capture[0], "anyerror")
          line("const int32_t v_#{capture[0]} = #{r}.err;")
        end
        case fallback
        in Return | Break | Continue then gen_stmt(fallback)
        in Block then gen_block(fallback)
        else
          fb = expr(fallback)
          if out.nil?
            line("#{fb};") unless fb.empty?
          else
            line("#{out} = #{coerce(fb, fallback.ty, e.ty)};")
          end
        end
        @locals.pop
        @indent -= 1
        if out.nil?
          line("}")
          return ""
        end
        line("} else {")
        line("    #{out} = #{r}.value;")
        line("}")
        out
      else
        raise "codegen: unhandled expression #{e.class}"
      end
    end

    def binary(op, lhs, rhs)
      if ARITH_FN.key?(op)
        a = expr(lhs)
        b = expr(rhs)
        return "(#{a} #{op} #{b})" if FLOAT_C.key?(lhs.ty)
        return "#{int_op(op, lhs.ty)}(#{a}, #{b})"
      end
      if op == "and" || op == "or"
        a = expr(lhs)
        b, pre = capture { expr(rhs) }
        return "(#{a} #{op == 'and' ? '&&' : '||'} #{b})" if pre.empty?
        # The right side needs temporaries: evaluate it only when needed.
        r = tmp
        line("bool #{r} = #{a};")
        line(op == "and" ? "if (#{r}) {" : "if (!#{r}) {")
        @indent += 1
        b, pre = capture { expr(rhs) }
        emit_raw(pre)
        line("#{r} = #{b};")
        @indent -= 1
        line("}")
        return r
      end
      a = expr(lhs)
      b = expr(rhs)
      if lhs.ty == "str"
        call = "#{helper('egg_str_eq')}(#{a}, #{b})"
        return op == "==" ? call : "(!#{call})"
      end
      "(#{a} #{op} #{b})"
    end

    # Arguments are evaluated left to right into the call; a non-void result
    # is hoisted into a temporary, so the call happens here and now.
    def call(c_name, args, params, receiver, ret)
      codes = receiver.dup
      args.each_with_index do |a, i|
        pt = params[i][0]
        codes << case a
                 in AddrOf[expr: place] then "&#{lvalue(place)}"
                 in SliceExpr then slice_expr(a)
                 else coerce(expr(a), a.ty, pt)
                 end
      end
      text = "#{c_name}(#{codes.join(', ')})"
      return text if ret == "void"
      hoist(text, ret)
    end

    # out.print(x), a.concat(s, t), a.int_str(n). The receiver carries no
    # data but is still evaluated, first, like any receiver.
    def cap_call(m, obj, args, ret)
      recv = expr(obj)
      codes = args.map { |a| expr(a) }
      text = case m
             when "Io.print"
               t = args[0].ty
               case t
               when "bool" then "#{helper('egg_print_bool')}(#{codes[0]})"
               when "str" then "#{helper('egg_print_str')}(#{codes[0]})"
               when "i64" then "#{helper('egg_print_i64')}(#{codes[0]})"
               when "i8", "i16", "i32" then "#{helper('egg_print_i64')}((int64_t)#{codes[0]})"
               when "u8", "u16", "u32", "u64", "usize" then "#{helper('egg_print_u64')}((uint64_t)#{codes[0]})"
               when "f32", "f64" then "#{helper('egg_print_float')}((double)#{codes[0]}, #{t == 'f32'})"
               else
                 @enum_names[t] = true
                 "#{helper('egg_print_cstr')}(#{@types[t].c_name}_names[#{codes[0]}])"
               end
             when "Allocator.create"
               # A copy of the value in the arena.
               t = args[0].ty
               ptr = tmp
               line("#{c_type(t)} *#{ptr} = (#{c_type(t)} *)#{helper('egg_alloc')}((int64_t)sizeof(#{c_type(t)}));")
               line("*#{ptr} = #{codes[0]};")
               ptr
             when "Allocator.alloc"
               # n copies of v in a new buffer
               elem = @types[ret].elem
               b = tmp
               line("#{c_type(ret)} #{b};")
               line("#{b}.len = #{codes[0]};")
               line("#{b}.ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(NULL, #{b}.len, sizeof(#{c_type(elem)}));")
               v = hoist(codes[1], elem)
               i = tmp
               line("for (int64_t #{i} = 0; #{i} < #{b}.len; #{i}++) #{b}.ptr[#{i}] = #{v};")
               b
             when "Allocator.free"
               t = args[0].ty
               info = @types[t]
               info.kind == :buf && !@checker.owned?(info.elem) ? "free(#{codes[0]}.ptr)" : "#{drop(t)}(#{codes[0]})"
             when "Allocator.resize"
               # new elements, if it grows, are copies of v
               buf = args[0].ty
               elem = @types[buf].elem
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               n = hoist(codes[1], "i64")
               v = hoist(coerce(codes[2], args[2].ty, elem), elem)
               if @checker.owned?(elem)
                 # Elements cut off when it shrinks are freed first.
                 i = tmp
                 line("if (#{n} >= 0) for (int64_t #{i} = #{n}; #{i} < #{p}->len; #{i}++) #{drop(elem)}(#{p}->ptr[#{i}]);")
               end
               line("#{p}->ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(#{p}->ptr, #{n}, sizeof(#{c_type(elem)}));")
               i = tmp
               line("for (int64_t #{i} = #{p}->len; #{i} < #{n}; #{i}++) #{p}->ptr[#{i}] = #{v};")
               line("#{p}->len = #{n};")
               "((void)0)"
             when "Allocator.push"
               # moved in at the end, one more element
               buf = args[0].ty
               elem = @types[buf].elem
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               v = hoist(coerce(codes[1], args[1].ty, elem), elem)
               line("#{p}->ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(#{p}->ptr, #{p}->len + 1, sizeof(#{c_type(elem)}));")
               line("#{p}->ptr[#{p}->len] = #{v};")
               line("#{p}->len++;")
               "((void)0)"
             when "Allocator.pop"
               # the last element moved out, or null; the memory stays
               buf = args[0].ty
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .has = false };")
               line("if (#{p}->len > 0) { #{p}->len--; #{r}.value = #{p}->ptr[#{p}->len]; #{r}.has = true; }")
               r
             when "Allocator.concat" then "#{helper('egg_concat')}(#{codes[0]}, #{codes[1]})"
             when "Allocator.int_str"
               if args[0].ty.start_with?("i")
                 "#{helper('egg_int_str')}((int64_t)#{codes[0]})"
               else
                 "#{helper('egg_uint_str')}((uint64_t)#{codes[0]})"
               end
             when "Allocator.cstr" then "#{helper('egg_cstr')}(#{codes[0]})"
             when "Allocator.str_from_c" then "#{helper('egg_str_from_c')}(#{codes[0]})"
             when "Allocator.float_str" then "#{helper('egg_float_str')}((double)#{codes[0]}, #{args[0].ty == 'f32'})"
             else raise "codegen: unknown capability method #{m}"
             end
      text = "((void)#{recv}, #{text})"
      return text if ret == "void"
      hoist(text, ret)
    end

    def builtin(e, name, args)
      a = args[0]
      case name
      when "ptrAdd" then "(#{expr(a)} + #{expr(args[1])})"
      when "ptrCast" then "((#{c_type(e.ty)})(void *)#{expr(args[1])})"
      when "strPtr" then "((uint8_t *)#{expr(a)}.ptr)"
      when "intFromPtr" then "((size_t)(uintptr_t)#{expr(a)})"
      when "ptrFromInt" then "((#{c_type(e.ty)})(uintptr_t)#{expr(args[1])})"
      when "as"
        x = args[1]
        code = expr(x)
        return code if x.ty == e.ty
        return float_conv(x.ty, e.ty, code) if FLOAT_C.key?(x.ty) || FLOAT_C.key?(e.ty)
        as_conv(x.ty, e.ty, code)
      when "len"
        code = expr(a)
        len = e.info[:len]
        len.nil? ? "#{code}.len" : "((void)#{code}, INT64_C(#{len}))"
      when "sizeOf"
        "((int64_t)sizeof(#{c_type(e.info[:type])}))"
      when "typeName"
        name = e.info[:type]
        @need_str = true
        "((egg_str){ #{c_string(name)}, #{name.bytesize} })"
      when "drop" then "((void)#{expr(a)})"
      when "errorName"
        @need_str = true
        @need_error_names = true
        "egg_error_strs[#{expr(a)}]"
      when "replace", "take"
        # The place first, left to right; the value cannot change it (E117).
        t = e.ty
        p = tmp
        line("#{c_type(t)} *#{p} = &#{lvalue(a.expr)};")
        v = name == "take" ? empty_buf(t) : hoist(coerce(expr(args[1]), args[1].ty, t), t)
        old = tmp
        line("#{c_type(t)} #{old} = *#{p};")
        line("*#{p} = #{v};")
        old
      when "splat"
        info = @types[e.ty]
        v = hoist(expr(a), info.elem)
        out = tmp
        i = tmp
        line("#{c_type(e.ty)} #{out};")
        line("for (int64_t #{i} = 0; #{i} < #{info.len}; #{i}++) #{out}.a[#{i}] = #{v};")
        out
      end
    end

    # A struct value to read a field from: places are read in place,
    # other expressions (calls) are already hoisted temporaries.
    def struct_value(obj)
      place?(obj) ? lvalue(obj) : expr(obj)
    end

    def index_expr(obj, index, len)
      t = obj.ty
      base = place?(obj) ? lvalue(obj) : expr(obj)
      i = expr(index)
      if t == "str"
        s = place?(obj) ? base : base
        return "((int64_t)(unsigned char)#{s}.ptr[#{helper('egg_index')}(#{i}, #{s}.len)])"
      end
      if %i[slice buf].include?(@types[t].kind)
        return "#{base}.ptr[#{helper('egg_index')}(#{i}, #{base}.len)]"
      end
      "#{base}.a[#{helper('egg_index')}(#{i}, INT64_C(#{len}))]"
    end

    def slice_expr(e)
      obj = e.obj
      t = obj.ty
      base = place?(obj) ? lvalue(obj) : hoist(expr(obj), t)
      lo = hoist(expr(e.lo), "i64")
      info = @types[t]
      len = if t == "str" || %i[slice buf].include?(info.kind) then "#{base}.len" else "INT64_C(#{info.len})" end
      hi = e.hi.nil? ? hoist(len, "i64") : hoist(expr(e.hi), "i64")
      line("#{helper('egg_slice_check')}(#{lo}, #{hi}, #{len});")
      if t == "str"
        "((egg_str){ #{base}.ptr + #{lo}, #{hi} - #{lo} })"
      elsif %i[slice buf].include?(info.kind)
        "((#{c_type(e.ty)}){ #{base}.ptr + #{lo}, #{hi} - #{lo} })"
      else
        "((#{c_type(e.ty)}){ #{base}.a + #{lo}, #{hi} - #{lo} })"
      end
    end

    # Is e a place (variable, field of a place, element of a place)?
    def place?(e)
      case e
      in Var[info:] then !info.nil? && info[:local] == true
      in Deref then true
      in Field[obj:, info:] then (info.nil? || (info[:enum_index].nil? && info[:union_tag].nil?)) && place?(obj)
      in Index[obj:] then place?(obj) && obj.ty != "str" && @types[obj.ty]&.kind == :array
      else false
      end
    end

    def lvalue(e)
      case e
      in Var[name:] then var_ref(name)
      in Deref[expr: ptr]
        # Checked: a null pointer panics instead of crashing.
        p = place?(ptr) ? lvalue(ptr) : hoist(expr(ptr), ptr.ty)
        "(*(#{p} != NULL ? #{p} : (#{c_type(ptr.ty)})#{helper('egg_null_deref')}()))"
      in Field[obj:, name:] then "#{lvalue(obj)}.f_#{name}"
      in Index[obj:, index:, info:]
        if @types[obj.ty]&.kind == :buf
          b = lvalue(obj)
          "#{b}.ptr[#{helper('egg_index')}(#{expr(index)}, #{b}.len)]"
        else
          "#{lvalue(obj)}.a[#{helper('egg_index')}(#{expr(index)}, INT64_C(#{info[:len]}))]"
        end
      else raise "codegen: not a place: #{e.class}"
      end
    end

    def var_ref(name)
      _, inout = local(name)
      inout ? "(*v_#{name})" : "v_#{name}"
    end

    def local(name)
      i = @locals.length - 1
      while i >= 0
        t = @locals[i][name]
        return t unless t.nil?
        i -= 1
      end
      raise "codegen: unknown local #{name}"
    end
  end
