    def c_type(t)
      case t
      when "i64" then "int64_t"
      when "bool" then "bool"
      when "void" then "void"
      when "anyerror" then "int32_t"
      when "str"
        @need_str = true
        "egg_str"
      when "Io"
        @need_cap[t] = true
        "egg_io"
      when "Allocator"
        @need_cap[t] = true
        "egg_allocator"
      when "Fs"
        @need_cap[t] = true
        "egg_fs"
      when "Args"
        @need_cap[t] = true
        "egg_args"
      when "Reader", "Writer", "DirReader", "Net", "Addr", "Threads", "Thread", "Clock", "Random"
        @need_cap[t] = true
        "egg_#{t.downcase}"
      when "TcpConn", "TcpListener", "UdpSocket"
        @need_cap[t] = true
        { "TcpConn" => "egg_tcp_conn", "TcpListener" => "egg_tcp_listener", "UdpSocket" => "egg_udp_socket" }[t]
      when *INT_C.keys then INT_C[t][0]
      when *FLOAT_C.keys then FLOAT_C[t]
      else
        info = @types[t]
        return "#{c_type(info.inner)} *" if info&.kind == :ptr
        raise "codegen: unknown type #{t}" if info.nil?
        info.c_name
      end
    end

    # Typedefs in dependency order: a struct after the types it holds by
    # value. Slices hold only pointers and come last.
    # Structs and unions are tagged and declared up front, so a pointer
    # field can name a struct that is defined later (or itself).
    def emit_types
      @checker.type_order.each do |c|
        info = @types[c]
        @out << "typedef struct #{info.c_name} #{info.c_name};\n" if %i[struct union].include?(info.kind)
      end
      @out << "\n" if @checker.type_order.any? { |c| %i[struct union].include?(@types[c].kind) }
      done = {}
      @checker.type_order.each { |c| emit_type(c, done) unless @types[c].kind == :slice }
      @checker.type_order.each { |c| emit_type(c, done) if @types[c].kind == :slice }
    end

    def emit_type(canon, done)
      info = @types[canon]
      return if info.nil? || info.kind == :prim || TypeChecker::FILE_TYPES.key?(canon) || done[canon]
      done[canon] = true
      # Marks name the declaring module's file; emitting a field's type
      # (maybe from another module) first must not change that. Arrays,
      # error unions and slices have no module and keep the enclosing one.
      saved = @line_file
      @line_file = file_of(info.mod) unless info.mod.nil?
      emit_type_body(canon, info, done)
      @line_file = saved
    end

    def emit_type_body(canon, info, done)
      case info.kind
      when :enum
        mark(info.line)
        @out << "typedef int32_t #{info.c_name};\n"
        (info.member_lines || []).uniq.each { |l| mark(l) unless l == info.line }
        @out << "\n" unless (info.member_lines || []).uniq == [info.line]
      when :struct
        info.fields.each { |_, t, _| emit_type(t, done) }
        mark(info.fn_line) unless info.fn_line.nil?
        @out << "/* #{canon} */\n" unless info.fn_line.nil?
        mark(info.return_line || info.line)
        @out << "struct #{info.c_name} {\n"
        if @checker.chan_end?(canon)
          @out << "    void *c;\n"
        elsif info.fields.empty?
          @out << "    char unused;\n"
        else
          info.fields.each do |name, t, l|
            mark(l)
            @out << "    #{c_type(t)} f_#{name};\n"
          end
        end
        @out << "};\n\n"
      when :union
        # { tag, union of payloads }; tag is the member's index.
        info.fields.each { |_, t, _| emit_type(t, done) unless t == "void" }
        mark(info.line)
        payloads = info.fields.reject { |_, t, _| t == "void" }
        @out << "struct #{info.c_name} {\n    int32_t tag;\n"
        unless payloads.empty?
          @out << "    union {\n"
          payloads.each { |n, t, _| @out << "        #{c_type(t)} m_#{n};\n" }
          @out << "    } u;\n"
        end
        info.fields.each { |_, _, l| mark(l) unless l == info.line }
        @out << "};\n\n"
      when :array
        emit_type(info.elem, done)
        @out << "typedef struct { #{c_type(info.elem)} a[#{info.len}]; } #{info.c_name};\n"
      when :err
        emit_type(info.inner, done)
        if info.inner == "void"
          @out << "typedef struct { int32_t err; } #{info.c_name};\n"
        else
          @out << "typedef struct { #{c_type(info.inner)} value; int32_t err; } #{info.c_name};\n"
        end
      when :opt
        emit_type(info.inner, done)
        @out << "typedef struct { #{c_type(info.inner)} value; bool has; } #{info.c_name};\n"
      when :slice
        emit_type(info.elem, done)
        @out << "typedef struct { const #{c_type(info.elem)} *ptr; int64_t len; } #{info.c_name};\n"
      when :buf
        emit_type(info.elem, done)
        # cap: elements allocated, so a.push grows by doubling.
        @out << "typedef struct { #{c_type(info.elem)} *ptr; int64_t len; int64_t cap; } #{info.c_name};\n"
      when :ptr
        # A struct or union target is declared up front; others are needed.
        emit_type(info.inner, done) unless %i[struct union].include?(@types[info.inner]&.kind)
      when :fn
        (info.fields + [info.inner]).each { |t| emit_type(t, done) unless %i[struct union].include?(@types[t]&.kind) }
        params = info.fields.empty? ? "void" : info.fields.each_with_index.map { |t, i| by_ref?(t, info.modes[i]) ? "#{c_type(t)} *" : c_type(t) }.join(", ")
        @out << "typedef #{c_type(info.inner)} (*#{info.c_name})(#{params});\n"
      end
    end

    # ---- functions ----------------------------------------------------

    def signature(sig)
      runtime = sig.func.params.reject { |p| p.mode == "comptime" }
      params = runtime.each_with_index.map do |p, i|
        t, mode = sig.params[i]
        by_ref?(t, mode) ? "#{c_type(t)} *v_#{p.name}" : "#{c_type(t)} v_#{p.name}"
      end
      params_text = params.empty? ? "void" : params.join(", ")
      # Not static: an unused function is not an error in Egg, and external
      # linkage keeps C's -Wunused-function quiet. Names are prefixed, so
      # they cannot clash with libc.
      "#{c_type(sig.ret)} #{sig.c_name}(#{params_text})"
    end

    # extern fn: the C function, declared with the exact C types.
    def extern_prototype(sig)
      params = sig.params.empty? ? "void" : sig.params.map { |t, _| c_type(t) }.join(", ")
      "#{c_type(sig.ret)} #{sig.c_name}(#{params})"
    end

    def gen_func(sig)
      @sig = sig
      @line_file = file_of(sig.func.mod)
      @tmp = 0
      @locals = [{}]
      runtime = sig.func.params.reject { |p| p.mode == "comptime" }
      runtime.each_with_index do |p, i|
        t, mode = sig.params[i]
        @locals.last[p.name] = [t, by_ref?(t, mode)]
      end
      mark(sig.func.line)
      @out << signature(sig) << " {\n"
      @indent = 1
      (sig.unused || []).each { |name| line("(void)v_#{name};") }
      @defers = [[]]
      @loop_marks = []
      sig.func.body.stmts.each { |s| gen_stmt(s) }
      emit_defers(0, false) unless ends_block?(sig.func.body.stmts)
      line("return (#{c_type('!void')}){ 0 };") if sig.ret == "!void"
      @out << "}\n\n"
      nil
    end

    # An inout parameter is a pointer, except an inout slice: the view is
    # passed by value and its elements are written through it.
    def by_ref?(t, mode)
      mode == "inout" && @types[t]&.kind != :slice
    end

    # main's capability parameters are made here: the runtime is where
    # capabilities come from.
    def gen_entry
      main = @checker.main_sig
      @line_file = file_of("")
      mark(main.func.line)
      if @used["egg_args_state"]
        @out << "int main(int argc, char **argv) {\n"
        @out << "    egg_args_init(argc, argv);\n"
      else
        @out << "int main(void) {\n"
      end
      # Once, before any thread could race to do it.
      @out << "    egg_stdin_binary();\n" if @used["egg_stdin_prepare"]
      @out << "    egg_net_start();\n" if @used["egg_net_start"]
      args = main.params.map { |t, _| "(#{c_type(t)}){ 0 }" }.join(", ")
      case main.ret
      when "i64"
        @out << "    return (int)#{main.c_name}(#{args});\n"
      when "!void"
        @out << "    #{c_type('!void')} r = #{main.c_name}(#{args});\n"
        @out << "    if (r.err) {\n"
        @out << "        fprintf(stderr, \"error: %s\\n\", egg_error_names[r.err]);\n"
        @out << "        return 1;\n"
        @out << "    }\n"
        @out << "    return 0;\n"
      else
        @out << "    #{main.c_name}(#{args});\n    return 0;\n"
      end
      @out << "}\n"
      nil
    end

    def gen_block(block)
      @locals << {}
      @defers << []
      @indent += 1
      block.stmts.each { |s| gen_stmt(s) }
      emit_defers(@defers.length - 1, false) unless ends_block?(block.stmts)
      @indent -= 1
      @defers.pop
      @locals.pop
      nil
    end

    # Does the block end by jumping away (so its end is never reached)?
    def ends_block?(stmts)
      [Return, Break, Continue].any? { |k| stmts.last.is_a?(k) }
    end

    def defers?
      @defers.any? { |f| !f.empty? }
    end

    # Emit the deferred expressions of the blocks from the innermost one
    # down to index `down`, last deferred first. error: whether errdefers
    # run (true, false, or a C condition tested at run time).
    def emit_defers(down, error)
      emitted = false
      i = @defers.length - 1
      while i >= down
        @defers[i].reverse_each do |d|
          next if d.err && error == false
          mark(d.line)
          code, pre = capture { expr(d.expr) }
          if d.err && error != true
            line("if (#{error}) {")
            @indent += 1
            emit_raw(pre.gsub(/^/, "    "))
            line("#{code};") unless code.empty?
            @indent -= 1
            line("}")
          else
            emit_raw(pre)
            line("#{code};") unless code.empty?
          end
          emitted = true
        end
        i -= 1
      end
      emitted
    end

    def line(text)
      @out << ("    " * @indent) << text << "\n"
      nil
    end

    # Attribute the C that follows to an .egg line (debug builds only).
    def mark(src_line)
      return if @line_file.nil? || src_line.nil?
      @out << "#line #{src_line} #{@line_file}\n"
      nil
    end

    def c_string(text)
      out = +"\""
      text.each_byte do |b|
        if b == 34 || b == 92
          out << "\\" << b.chr
        elsif b >= 32 && b < 127 && b != 63 # '?' escaped against trigraphs
          out << b.chr
        else
          out << format("\\%03o", b)
        end
      end
      out << "\""
    end

    def tmp
      @tmp += 1
      "_t#{@tmp}"
    end

    # Run the block with output going to a separate buffer; returns
    # [block's value, the lines it emitted].
    def capture
      saved = @out
      @out = +""
      value = yield
      [value, @out]
    ensure
      @out = saved
    end

    def emit_raw(text)
      @out << text
    end

    def declare_local(name, ty)
      @locals.last[name] = [ty, false]
    end

    # ---- statements ---------------------------------------------------

    def gen_stmt(stmt)
      mark(stmt.line)
      case stmt
      in VarDecl[name:, value:, ty:]
        code = coerce(expr(value), value.ty, ty)
        declare_local(name, ty)
        line("#{c_type(ty)} v_#{name} = #{code};")
      in Assign[name:, value:, target:]
        if target.nil?
          code = coerce(expr(value), value.ty, local(name)[0])
          line("#{var_ref(name)} = #{code};")
        else
          code = coerce(expr(value), value.ty, target.ty)
          line("#{lvalue(target)} = #{code};")
        end
      in If
        gen_if(stmt)
      in While[cond:, body:]
        @loop_marks << @defers.length
        c, pre = capture { cond(cond) }
        if pre.empty?
          line("while (#{c}) {")
        else
          line("while (1) {")
          @indent += 1
          c, pre = capture { cond(cond) }
          emit_raw(pre)
          line("if (!(#{c})) break;")
          @indent -= 1
        end
        gen_block(body)
        line("}")
        @loop_marks.pop
      in For
        gen_for(stmt)
      in Switch
        gen_switch(stmt)
      in Break
        mark(stmt.line) if emit_defers(@loop_marks.last, false)
        line("break;")
      in Continue
        mark(stmt.line) if emit_defers(@loop_marks.last, false)
        line("continue;")
      in Return[value:]
        gen_return(value, stmt.line)
      in Defer
        @defers.last << stmt
      in ExprStmt[expr: e, discard: true]
        code = expr(e)
        line("(void)(#{code});") unless code.empty?
      in ExprStmt[expr: e]
        code = expr(e)
        line("#{code};") unless code.empty?
      else
        raise "codegen: unhandled statement #{stmt.class}"
      end
    end

    def gen_return(value, src_line)
      ret = @sig.ret
      if value.nil?
        mark(src_line) if emit_defers(0, false)
        line(ret == "!void" ? "return (#{c_type(ret)}){ 0 };" : "return;")
      elsif !defers?
        line("return #{coerce(expr(value), value.ty, ret)};")
      else
        # The value first, then the defers, which may change what it came from.
        r = hoist(coerce(expr(value), value.ty, ret), ret)
        error = false
        error = value.is_a?(ErrorLit) || value.ty == "anyerror" ? true : (value.ty.start_with?("!") ? "#{r}.err" : false) if ret.start_with?("!")
        mark(src_line) if emit_defers(0, error)
        line("return #{r};")
      end
    end

    # if / else if / else chains become one flat C chain, unless an else-if
    # condition needs temporaries: then it nests inside the else.
    def gen_if(stmt)
      if stmt.cond.is_a?(BoolLit) && stmt.cond.value == true && stmt.else_body.nil?
        # always taken (a folded comptime if): a plain block
        line("{")
        gen_block(stmt.then_body)
        line("}")
        return
      end
      if stmt.capture.nil?
        c = cond(stmt.cond)
        line("if (#{c}) {")
        gen_block(stmt.then_body)
      else
        gen_capture(stmt)
      end
      tail = stmt.else_body
      closers = 0
      while tail.is_a?(If)
        unless tail.capture.nil?
          line("} else {")
          @indent += 1
          mark(tail.line)
          gen_if(tail)
          @indent -= 1
          tail = nil
          break
        end
        tc, pre = capture { cond(tail.cond) }
        if pre.empty? && @line_file.nil?
          line("} else if (#{tc}) {")
        elsif pre.empty?
          # A directive needs its own line, so split "} else if" around it.
          line("}")
          mark(tail.line)
          line("else if (#{tc}) {")
        else
          line("} else {")
          @indent += 1
          closers += 1
          mark(tail.line)
          tc, pre = capture { cond(tail.cond) }
          emit_raw(pre)
          line("if (#{tc}) {")
        end
        gen_block(tail.then_body)
        tail = tail.else_body
      end
      unless tail.nil?
        line("} else {")
        gen_block(tail)
      end
      line("}")
      closers.times do
        @indent -= 1
        line("}")
      end
    end

    # The start of if (x) |v| { ... }: the value is v for the block.
    def gen_capture(stmt)
      r = hoist(expr(stmt.cond), stmt.cond.ty)
      inner = @types[stmt.cond.ty].inner
      line("if (#{r}.has) {")
      @locals << {}
      declare_local(stmt.capture, inner)
      @indent += 1
      line("const #{c_type(inner)} v_#{stmt.capture} = #{r}.value;")
      @indent -= 1
      gen_block(stmt.then_body)
      @locals.pop
    end

    def gen_for(stmt)
      it = stmt.iter
      t = it.ty
      idx = tmp
      if t == "str"
        s = tmp
        line("egg_str #{s} = #{expr(it)};")
        @need_str = true
        len = "#{s}.len"
        item = "(uint8_t)#{s}.ptr[#{idx}]"
        elem = "u8"
      else
        info = @types[t]
        elem = info.elem
        ptr = tmp
        if info.kind == :array
          base = place?(it) ? lvalue(it) : hoist(expr(it), t)
          line("const #{c_type(elem)} *#{ptr} = #{base}.a;")
          len = "INT64_C(#{info.len})"
        else
          s = hoist(expr(it), t)
          line("const #{c_type(elem)} *#{ptr} = #{s}.ptr;")
          len = "#{s}.len"
        end
        item = "#{ptr}[#{idx}]"
        line("(void)#{ptr};") if stmt.var == "_"
      end
      line("for (int64_t #{idx} = 0; #{idx} < #{len}; #{idx}++) {")
      @loop_marks << @defers.length
      @locals << {}
      @indent += 1
      unless stmt.var == "_"
        declare_local(stmt.var, elem)
        line("const #{c_type(elem)} v_#{stmt.var} = #{item};")
      end
      unless stmt.index_var.nil? || stmt.index_var == "_"
        declare_local(stmt.index_var, "i64")
        line("const int64_t v_#{stmt.index_var} = #{idx};")
      end
      @indent -= 1
      gen_block(stmt.body)
      @locals.pop
      @loop_marks.pop
      line("}")
    end

    # switch becomes an if chain over the tag (not a C switch, so that a
    # `break` in an arm still leaves the enclosing loop).
    def gen_switch(stmt)
      subject = stmt.subject
      t = subject.ty
      info = @types[t]
      base = place?(subject) ? lvalue(subject) : hoist(expr(subject), t)
      tag = info&.kind == :union ? "#{base}.tag" : base
      # The checker proved the arms exhaustive, so the last arm needs no
      # test; C then also sees that every path returns.
      last = stmt.arms.length - 1
      stmt.arms.each_with_index do |arm, i|
        if arm.names.nil? || i == last
          if i.zero?
            mark(arm.line)
            line("{")
          else
            line("}")
            mark(arm.line)
            line("else {")
          end
        else
          test = arm.names.map do |n|
            idx = if t == "anyerror" then @checker.error_names.index(n.delete_prefix("error.")) + 1
                  elsif info.kind == :union then info.fields.index { |m, _| m == n }
                  else info.members.index(n)
                  end
            "#{tag} == #{idx}"
          end.join(" || ")
          if i.zero?
            mark(arm.line)
            line("if (#{test}) {")
          else
            line("}")
            mark(arm.line)
            line("else if (#{test}) {")
          end
        end
        @locals << {}
        unless arm.capture.nil? || arm.capture == "_"
          payload = info.fields.find { |m, _| m == arm.names[0] }[1]
          declare_local(arm.capture, payload)
          line("    const #{c_type(payload)} v_#{arm.capture} = #{base}.u.m_#{arm.names[0]};")
        end
        gen_block(arm.body)
        @locals.pop
      end
      line("}")
    end

    # ---- expressions --------------------------------------------------

    # A condition already sits inside if (...) / while (...), so drop the
    # outer parentheses that expr adds (clang warns on `if ((a == b))`).
    def cond(e)
      text = expr(e)
      if e.is_a?(Binary) && !ARITH_FN.key?(e.op) && text.start_with?("(") && text.end_with?(")")
        text[1...-1]
      else
        text
      end
    end

    # Evaluate code once into a temporary of type t; returns its name.
    def hoist(code, t)
      name = tmp
      line("#{c_type(t)} #{name} = #{code};")
      name
    end

    # Wrap a value for a !T slot: T -> { value, 0 }, error.X -> { .err = X }.
    def coerce(code, from, to)
      return code if to.nil? || from == to
      return text_as(code, from, to) if %w[str []u8].include?(to) && text_type?(from)
      return "((#{c_type(to)}){ .value = #{code}, .has = true })" if to.start_with?("?")
      return code unless to.start_with?("!")
      if from == "anyerror"
        "((#{c_type(to)}){ .err = #{code} })"
      else
        "((#{c_type(to)}){ .value = #{coerce(code, from, @types[to].inner)}, .err = 0 })"
      end
    end

    # A str, a []u8 or a Buf(u8).
    def text_type?(t)
      t == "str" || t == "[]u8" || (@types[t]&.kind == :buf && @types[t].elem == "u8")
    end

    # Text seen as a str or as a []u8: the same bytes, nothing copied.
    def text_as(code, from, to)
      v = code.match?(/\A[\w.>-]+\z/) ? code : hoist(code, from)
      if to == "str"
        @need_str = true
        "((egg_str){ (const char *)#{v}.ptr, #{v}.len })"
      else
        "((#{c_type(to)}){ (const uint8_t *)#{v}.ptr, #{v}.len })"
      end
    end

    def expr(e)
      case e
      in IntLit[value:]
        int_lit(value, e.ty)
      in FloatLit[text:]
        float_lit(text, e.ty)
      in BoolLit[value:]
        value ? "true" : "false"
      in StrLit[value:]
        @need_str = true
        "((egg_str){ #{c_string(value)}, #{value.bytesize} })"
      in Var[info: { fn_ref: String => c_name }]
        c_name
      in Var[info: { const: c }]
        expr(c.lit)
      in Field[info: { const: c }]
        expr(c.lit)
      in Var[name:]
        var_ref(name)
      in Unary[op:, operand:, info: { neg_lit: true }]
        # As a float, -0 keeps its sign: negate the literal, do not fold it.
        FLOAT_C.key?(e.ty) ? "(-#{int_lit(operand.value, e.ty)})" : int_lit(-operand.value, e.ty)
      in Unary[op: "~", operand:]
        "((#{INT_C[e.ty][0]})~#{expr(operand)})"
      in Unary[op:, operand:]
        if op != "-" then "(!#{expr(operand)})"
        elsif FLOAT_C.key?(e.ty) then "(-#{expr(operand)})"
        else "#{int_op('neg', e.ty)}(#{expr(operand)})"
        end
      in Binary[op:, lhs:, rhs:]
        binary(op, lhs, rhs)
      in Call[name:, info: { indirect: true } => info]
        call(var_ref(name), info[:args], info[:params], [], e.ty)
      in Call[info:]
        call(info[:c_name], info[:args], info[:params], [], e.ty)
      in MethodCall[obj:, info: { cap_method: String => m }]
        cap_call(m, obj, e.args, e.ty)
      in MethodCall[obj:, name:, info: { field_call: true } => info]
        call("#{struct_value(obj)}.f_#{name}", info[:args], info[:params], [], e.ty)
      in MethodCall[obj:, info:]
        recv = []
        unless info[:static]
          recv << (info[:self_inout] ? "&#{lvalue(obj)}" : in_order(expr(obj), obj, info[:args]))
        end
        call(info[:c_name], info[:args], info[:params], recv, e.ty)
      in Builtin[name:, args:]
        builtin(e, name, args)
      in Field[obj:, name:, info:]
        return empty_buf(e.ty) if info[:buf_empty]
        return "((#{c_type(e.ty)}){ .tag = #{info[:union_tag]} })" unless info[:union_tag].nil?
        return "((#{c_type(e.ty)})#{info[:enum_index]})" unless info[:enum_index].nil?
        "#{struct_value(obj)}.f_#{name}"
      in Index[obj:, index:]
        index_expr(obj, index, e.info[:len])
      in SliceExpr
        slice_expr(e)
      in StructLit[fields:, info: { union_tag: Integer => tag, member: String => member }]
        value = fields[0][1]
        payload = @types[e.ty].fields[tag][1]
        "((#{c_type(e.ty)}){ .tag = #{tag}, .u.m_#{member} = #{coerce(expr(value), value.ty, payload)} })"
      in StructLit[fields:]
        info = @types[e.ty]
        inits = fields.each_with_index.map do |(fname, value, _, _), i|
          ftype = info.fields.find { |n, _| n == fname }[1]
          later = fields[(i + 1)..].map { |f| f[1] }
          ".f_#{fname} = #{coerce(in_order(expr(value), value, later), value.ty, ftype)}"
        end
        inits = ["0"] if inits.empty?
        "((#{c_type(e.ty)}){ #{inits.join(', ')} })"
      in ArrayLit[items:]
        elem = @types[e.ty].elem
        vals = items.each_with_index.map { |it, i| coerce(in_order(expr(it), it, items[(i + 1)..]), it.ty, elem) }
        "((#{c_type(e.ty)}){ { #{vals.join(', ')} } })"
      in EnumLit[info: { buf_empty: true }]
        empty_buf(e.ty)
      in EnumLit[info: { union_tag: Integer => tag }]
        "((#{c_type(e.ty)}){ .tag = #{tag} })"
      in EnumLit[info:]
        "((#{c_type(e.ty)})#{info[:enum_index]})"
      in ErrorLit[info:]
        info[:error_id].to_s
      in NullLit
        @types[e.ty].kind == :opt ? "((#{c_type(e.ty)}){ .has = false })" : "((#{c_type(e.ty)})0)"
      in AddrOf[expr: place]
        "(&#{lvalue(place)})"
      in Deref
        lvalue(e)
      in Try[expr: inner]
        r = hoist(expr(inner), inner.ty)
        if defers?
          line("if (#{r}.err) {")
          @indent += 1
          emit_defers(0, true)
          line("return (#{c_type(@sig.ret)}){ .err = #{r}.err };")
          @indent -= 1
          line("}")
        else
          line("if (#{r}.err) return (#{c_type(@sig.ret)}){ .err = #{r}.err };")
        end
        e.ty == "void" ? "" : "#{r}.value"
      in IfExpr[cond: c, then_expr:, else_expr:]
        a, pre_a = capture { coerce(expr(then_expr), then_expr.ty, e.ty) }
        b, pre_b = capture { coerce(expr(else_expr), else_expr.ty, e.ty) }
        test = cond(c)
        return "(#{test} ? #{a} : #{b})" if pre_a.empty? && pre_b.empty?
        # A branch needs temporaries: compute only the one that is taken.
        out = tmp
        line("#{c_type(e.ty)} #{out};")
        line("if (#{test}) {")
        # Each branch's lines, captured above, go one level in.
        emit_raw(pre_a.gsub(/^(?=.)/, "    "))
        line("    #{out} = #{a};")
        line("} else {")
        emit_raw(pre_b.gsub(/^(?=.)/, "    "))
        line("    #{out} = #{b};")
        line("}")
        out
      in Orelse[expr: inner, fallback:]
        r = hoist(expr(inner), inner.ty)
        out = tmp
        line("#{c_type(e.ty)} #{out};")
        line("if (!#{r}.has) {")
        @indent += 1
        case fallback
        in Return | Break | Continue then gen_stmt(fallback)
        in Block then gen_block(fallback)
        else line("#{out} = #{coerce(expr(fallback), fallback.ty, e.ty)};")
        end
        @indent -= 1
        line("} else {")
        line("    #{out} = #{r}.value;")
        line("}")
        out
      in Catch[expr: inner, fallback:, capture:]
        r = hoist(expr(inner), inner.ty)
        out = nil
        unless e.ty == "void"
          out = tmp
          line("#{c_type(e.ty)} #{out};")
        end
        line("if (#{r}.err) {")
        @indent += 1
        @locals << {}
        unless capture.nil? || capture[0] == "_"
          declare_local(capture[0], "anyerror")
          line("const int32_t v_#{capture[0]} = #{r}.err;")
        end
        case fallback
        in Return | Break | Continue then gen_stmt(fallback)
        in Block then gen_block(fallback)
        else
          fb = expr(fallback)
          if out.nil?
            line("#{fb};") unless fb.empty?
          else
            line("#{out} = #{coerce(fb, fallback.ty, e.ty)};")
          end
        end
        @locals.pop
        @indent -= 1
        if out.nil?
          line("}")
          return ""
        end
        line("} else {")
        line("    #{out} = #{r}.value;")
        line("}")
        out
      else
        raise "codegen: unhandled expression #{e.class}"
      end
    end

    def binary(op, lhs, rhs)
      if ARITH_FN.key?(op)
        a = in_order(expr(lhs), lhs, [rhs])
        b = expr(rhs)
        return "(#{a} #{op} #{b})" if FLOAT_C.key?(lhs.ty)
        return "#{int_op(op, lhs.ty)}(#{a}, #{b})"
      end
      if op == "&" || op == "|" || op == "^"
        a = in_order(expr(lhs), lhs, [rhs])
        return "((#{INT_C[lhs.ty][0]})(#{a} #{op} #{expr(rhs)}))"
      end
      if op == "<<" || op == ">>"
        a = in_order(expr(lhs), lhs, [rhs])
        return "#{shift_op(op, lhs.ty, rhs.ty)}(#{a}, #{expr(rhs)})"
      end
      if op == "and" || op == "or"
        a = expr(lhs)
        b, pre = capture { expr(rhs) }
        return "(#{a} #{op == 'and' ? '&&' : '||'} #{b})" if pre.empty?
        # The right side needs temporaries: evaluate it only when needed.
        r = tmp
        line("bool #{r} = #{a};")
        line(op == "and" ? "if (#{r}) {" : "if (!#{r}) {")
        @indent += 1
        b, pre = capture { expr(rhs) }
        emit_raw(pre)
        line("#{r} = #{b};")
        @indent -= 1
        line("}")
        return r
      end
      a = in_order(expr(lhs), lhs, [rhs])
      b = expr(rhs)
      if text_type?(lhs.ty) && op != "==" && op != "!="
        return "(#{helper('egg_str_cmp')}(#{coerce(a, lhs.ty, 'str')}, #{coerce(b, rhs.ty, 'str')}) #{op} 0)"
      end
      if text_type?(lhs.ty)
        call = "#{helper('egg_str_eq')}(#{coerce(a, lhs.ty, 'str')}, #{coerce(b, rhs.ty, 'str')})"
        return op == "==" ? call : "(!#{call})"
      end
      "(#{a} #{op} #{b})"
    end

    # Operands run left to right. A later operand may change a variable
    # through an inout argument (&x) of a call inside it, and C would read
    # an earlier operand that names x only afterwards: so when one may,
    # the earlier value is taken into a temporary first. (A borrow of what
    # a later operand changes is E117, so copying it here is sound.)
    def in_order(code, e, later)
      return code if constant?(e) || e.is_a?(AddrOf) || later.none? { |l| !@checker.inout_writes(l).empty? }
      hoist(code, e.ty)
    end

    def constant?(e)
      case e
      in IntLit | FloatLit | BoolLit | StrLit | EnumLit | NullLit | ErrorLit then true
      else false
      end
    end

    # Arguments are evaluated left to right into the call; a non-void result
    # is hoisted into a temporary, so the call happens here and now.
    def call(c_name, args, params, receiver, ret)
      codes = receiver.dup
      args.each_with_index do |a, i|
        pt = params[i][0]
        later = args[(i + 1)..]
        codes << case a
                 in AddrOf[expr: SliceExpr => s] then slice_expr(s)
                 in AddrOf[expr: place] then "&#{lvalue(place)}"
                 in SliceExpr then coerce(in_order(slice_expr(a), a, later), a.ty, pt)
                 else coerce(in_order(expr(a), a, later), a.ty, pt)
                 end
      end
      text = "#{c_name}(#{codes.join(', ')})"
      return text if ret == "void"
      hoist(text, ret)
    end

    # The error id of what an egg_fs_ helper returned; 0 is success.
    def fs_error(code)
      ids = TypeChecker::FS_ERRORS.map { |n| @checker.error_names.index(n) + 1 }
      "((const int32_t[]){ 0, #{ids.join(', ')} })[#{code}]"
    end

    # The longest line wanted, checked, or -1 for no limit.
    def line_limit(m, codes)
      m.end_with?("_max") ? "#{helper('egg_line_max')}(#{codes[2]})" : "INT64_C(-1)"
    end

    def line_too_long(m)
      m.end_with?("_max") ? @checker.error_names.index("LineTooLong") + 1 : 0
    end

    # The error id of an index into NET_ERRORS (from 1); 0 is success.
    def net_error(code)
      ids = TypeChecker::NET_ERRORS.map { |n| @checker.error_names.index(n) + 1 }
      "((const int32_t[]){ 0, #{ids.join(', ')} })[#{code}]"
    end

    def chan_call(m, obj, recv, args, ret)
      if m == "Threads.channel"
        elem = @types[ret].elem
        return hoist("((void)#{recv}, (#{c_type(ret)}){ #{helper('egg_chan_new')}(sizeof(#{c_type(elem)}), #{expr(args[1])}) })", ret)
      end
      c = "#{hoist(recv, obj.ty)}.c"
      case m
      when "Sender.send"
        elem = @types[obj.ty].elem
        v = hoist(coerce(expr(args[0]), args[0].ty, elem), elem)
        "#{helper('egg_chan_send')}(#{c}, &#{v})"
      when "Sender.clone", "Receiver.sender"
        hoist("(#{c_type(ret)}){ #{helper('egg_chan_sender')}(#{c}) }", ret)
      when "Receiver.clone"
        hoist("(#{c_type(ret)}){ #{helper('egg_chan_receiver')}(#{c}) }", ret)
      when "Sender.close"
        "#{helper('egg_chan_tx_close')}(#{c})"
      when "Receiver.close"
        "#{helper('egg_chan_rx_close')}(#{c}, #{@checker.owned?(@types[obj.ty].elem)})"
      when "Receiver.recv"
        r = tmp
        line("#{c_type(ret)} #{r} = { .has = false };")
        line("#{r}.has = #{helper('egg_chan_recv')}(#{c}, &#{r}.value);")
        r
      when "Receiver.recv_timeout"
        r = tmp
        line("#{c_type(ret)} #{r} = { .has = false };")
        line("#{r}.has = #{helper('egg_chan_recv_for')}(#{c}, &#{r}.value, #{expr(args[0])});")
        r
      end
    end

    # The FILE of a Reader or a Writer, computed once.
    def file_of_value(recv, obj)
      "#{hoist(recv, obj.ty)}.f"
    end

    def io_failed
      @checker.error_names.index("IoFailed") + 1
    end

    # io.print(x), a.concat(s, t), a.int_str(n). The receiver carries no
    # data but is still evaluated, first, like any receiver.
    def cap_call(m, obj, args, ret)
      recv = expr(obj)
      return chan_call(m, obj, recv, args, ret) if m.start_with?("Sender.", "Receiver.") || m == "Threads.channel"
      codes = args.each_with_index.map { |a, i| in_order(expr(a), a, args[(i + 1)..]) }
      text = case m
             when "Io.print"
               # All arguments are computed first (codes), then printed one
               # after another; only the last ends the line.
               locked_print(args, codes, "stdout")
             when "Io.eprint"
               # Whatever was printed before comes first, also when both
               # streams go to one place (2>&1). Standard error has no buffer.
               line("fflush(stdout);")
               locked_print(args, codes, "stderr")
             when "Io.read_line", "Io.read_line_max"
               line("(void)#{codes[0]};")
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               s = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{helper('egg_stdin_prepare')}();")
               max = line_limit(m, codes)
               line("int #{s} = #{helper('egg_read_line')}(stdin, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{max});")
               line("#{r}.value = #{s} > 0;")
               line("if (#{s} < 0) #{r}.err = #{s} == -2 ? #{line_too_long(m)} : #{io_failed};")
               r
             when "Io.read_all"
               line("(void)#{codes[0]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{helper('egg_stdin_prepare')}();")
               line("if (!#{helper('egg_read_all')}(stdin, &#{r}.value.ptr, &#{r}.value.len, &#{r}.value.cap)) #{r}.err = #{io_failed};")
               r
             when "Args.len"
               "#{helper('egg_args_len')}()"
             when "Clock.now"
               "#{helper('egg_clock_now')}()"
             when "Clock.monotonic"
               "#{helper('egg_clock_monotonic')}()"
             when "Random.fill"
               b = tmp
               line("#{c_type(args[0].ty)} *#{b} = #{codes[0]};")
               "#{helper('egg_random_fill')}(#{b}->ptr, #{b}->len)"
             when "Args.get"
               "#{helper('egg_args_get')}(#{codes[0]})"
             when "Args.env"
               r = tmp
               line("#{c_type(ret)} #{r} = { .has = false };")
               line("#{r}.has = #{helper('egg_args_env')}(#{coerce(codes[0], args[0].ty, 'str')}, &#{r}.value);")
               r
             when "Threads.spawn"
               ft = @types[args[0].ty]
               name = "egg_spawn_#{@spawns.length}"
               fields = ["#{c_type(args[0].ty)} f;"] + ft.fields.each_with_index.map { |t, i| "#{c_type(t)} a#{i};" }
               call_args = ft.fields.each_index.map { |i| "c.a#{i}" }.join(", ")
               helper("egg_thread_base")
               @spawns << <<~C
                 typedef struct { #{fields.join(' ')} } #{name};
                 static EGG_THREAD_FN(#{name}_run) {
                     #{name} c = *(#{name} *)arg;
                     free(arg);
                     c.f(#{call_args});
                     return 0;
                 }
               C
               p = tmp
               line("#{name} *#{p} = (#{name} *)#{helper('egg_buf_resize')}(NULL, 1, sizeof(#{name}));")
               line("#{p}->f = #{codes[0]};")
               ft.fields.each_with_index { |t, i| line("#{p}->a#{i} = #{coerce(codes[i + 1], args[i + 1].ty, t)};") }
               "#{helper('egg_thread_start')}(#{name}_run, #{p})"
             when "Thread.join", "Thread.detach"
               "#{helper(m == 'Thread.join' ? 'egg_thread_join' : 'egg_thread_detach')}(#{recv})"
             when "Net.tcp_connect", "Net.tcp_listen", "Net.udp_bind", "Net.resolve"
               host = coerce(codes[0], args[0].ty, "str")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               call = case m
                      when "Net.tcp_connect" then "#{helper('egg_tcp_connect')}(#{host}, #{codes[1]}, &#{r}.value.c)"
                      when "Net.tcp_listen" then "#{helper('egg_net_bind')}(#{host}, #{codes[1]}, SOCK_STREAM, &#{r}.value.s)"
                      when "Net.udp_bind" then "#{helper('egg_net_bind')}(#{host}, #{codes[1]}, SOCK_DGRAM, &#{r}.value.s)"
                      else "#{helper('egg_net_resolve')}(#{host}, #{codes[1]}, &#{r}.value)"
                      end
               line("#{r}.err = #{net_error(call)};")
               r
             when "TcpConn.read_line", "TcpConn.read_line_max"
               line("(void)#{codes[0]};")
               c = hoist(recv, obj.ty)
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               s = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               max = line_limit(m, codes)
               line("int #{s} = #{helper('egg_tcp_read_line')}(#{c}.c, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{max});")
               line("if (#{s} < 0) #{r}.err = #{net_error("-#{s}")}; else #{r}.value = #{s} > 0;")
               r
             when "TcpConn.read"
               line("(void)#{codes[0]};")
               c = hoist(recv, obj.ty)
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.value = #{helper('egg_tcp_read')}(#{c}.c, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{codes[2]});")
               line("if (#{r}.value < 0) #{r}.err = #{net_error("-#{r}.value")};")
               r
             when "TcpConn.read_all"
               line("(void)#{codes[0]};")
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_tcp_read_all')}(#{c}.c, &#{r}.value.ptr, &#{r}.value.len, &#{r}.value.cap)")};")
               r
             when "TcpConn.write"
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_tcp_write')}(#{c}.c, #{coerce(codes[0], args[0].ty, 'str')})")};")
               r
             when "TcpConn.set_timeout", "UdpSocket.set_timeout"
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               call = m == "TcpConn.set_timeout" ? "#{helper('egg_tcp_timeout')}(#{c}.c, #{codes[0]})" : "#{helper('egg_net_timeout')}((egg_sock)#{c}.s, #{codes[0]})"
               line("#{r}.err = #{net_error(call)};")
               r
             when "TcpConn.clone"
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_tcp_clone')}(#{c}.c, &#{r}.value.c)")};")
               r
             when "TcpConn.close"
               "#{helper('egg_tcp_close')}(#{hoist(recv, obj.ty)}.c)"
             when "TcpListener.close", "UdpSocket.close"
               "#{helper('egg_net_close')}((egg_sock)#{hoist(recv, obj.ty)}.s)"
             when "TcpListener.accept"
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_tcp_accept')}(#{c}.s, &#{r}.value.c)")};")
               r
             when "TcpListener.port", "UdpSocket.port"
               "#{helper('egg_net_port')}(#{hoist(recv, obj.ty)}.s)"
             when "UdpSocket.recv_from"
               line("(void)#{codes[0]};")
               c = hoist(recv, obj.ty)
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_udp_recv')}(#{c}.s, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{codes[2]}, &#{r}.value)")};")
               r
             when "UdpSocket.send_to"
               c = hoist(recv, obj.ty)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{net_error("#{helper('egg_udp_send')}(#{c}.s, #{codes[0]}, #{coerce(codes[1], args[1].ty, 'str')})")};")
               r
             when "Addr.port"
               "#{helper('egg_addr_port')}(#{hoist(recv, obj.ty)})"
             when "Fs.open", "Fs.create", "Fs.append"
               mode = { "Fs.open" => "rb", "Fs.create" => "wb", "Fs.append" => "ab" }[m]
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{fs_error("#{helper('egg_fs_handle')}(#{coerce(codes[0], args[0].ty, 'str')}, \"#{mode}\", &#{r}.value.f)")};")
               r
             when "Reader.read_line", "Reader.read_line_max"
               line("(void)#{codes[0]};")
               f = file_of_value(recv, obj)
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               s = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               max = line_limit(m, codes)
               line("int #{s} = #{helper('egg_read_line')}(#{f}, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{max});")
               line("#{r}.value = #{s} > 0;")
               line("if (#{s} < 0) #{r}.err = #{s} == -2 ? #{line_too_long(m)} : #{io_failed};")
               r
             when "Reader.read_all"
               line("(void)#{codes[0]};")
               f = file_of_value(recv, obj)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("if (!#{helper('egg_read_all')}(#{f}, &#{r}.value.ptr, &#{r}.value.len, &#{r}.value.cap)) #{r}.err = #{io_failed};")
               r
             when "Reader.read"
               line("(void)#{codes[0]};")
               f = file_of_value(recv, obj)
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.value = #{helper('egg_read_bytes')}(#{f}, &#{b}->ptr, &#{b}->len, &#{b}->cap, #{codes[2]});")
               line("if (#{r}.value < 0) #{r}.err = #{io_failed};")
               r
             when "Reader.close", "Writer.close"
               "(void)fclose(#{file_of_value(recv, obj)})"
             when "Writer.flush"
               f = file_of_value(recv, obj)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("if (fflush(#{f}) != 0) #{r}.err = #{io_failed};")
               r
             when "Writer.print"
               f = file_of_value(recv, obj)
               locked_print(args, codes, f)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("if (ferror(#{f})) #{r}.err = #{io_failed};")
               r
             when "Writer.write"
               f = file_of_value(recv, obj)
               v = hoist(coerce(codes[0], args[0].ty, "str"), "str")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("if (fwrite(#{v}.ptr, 1, (size_t)#{v}.len, #{f}) != (size_t)#{v}.len) #{r}.err = #{io_failed};")
               r
             when "Fs.read"
               line("(void)#{codes[0]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{fs_error("#{helper('egg_fs_read')}(#{coerce(codes[1], args[1].ty, 'str')}, &#{r}.value.ptr, &#{r}.value.len, &#{r}.value.cap)")};")
               r
             when "Fs.write"
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{fs_error("#{helper('egg_fs_write')}(#{coerce(codes[0], args[0].ty, 'str')}, #{coerce(codes[1], args[1].ty, 'str')})")};")
               r
             when "Fs.remove_file", "Fs.remove_dir", "Fs.make_dir", "Fs.rename", "Fs.stat", "Fs.open_dir"
               path = coerce(codes[0], args[0].ty, "str")
               call = case m
                      when "Fs.remove_file", "Fs.remove_dir" then "#{helper('egg_fs_remove')}(#{path}, #{m == 'Fs.remove_dir' ? 1 : 0})"
                      when "Fs.make_dir" then "#{helper('egg_fs_mkdir')}(#{path})"
                      when "Fs.rename" then "#{helper('egg_fs_rename')}(#{path}, #{coerce(codes[1], args[1].ty, 'str')})"
                      when "Fs.stat" then "#{helper('egg_fs_stat')}(#{path}, &R.value.f_kind, &R.value.f_size)"
                      else "#{helper('egg_dir')}_open(#{path}, &R.value.d)"
                      end
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{fs_error(call.gsub('&R.', "&#{r}."))};")
               r
             when "Fs.real_path"
               line("(void)#{codes[0]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("#{r}.err = #{fs_error("#{helper('egg_fs_real')}(#{coerce(codes[1], args[1].ty, 'str')}, &#{r}.value.ptr, &#{r}.value.len, &#{r}.value.cap)")};")
               r
             when "DirReader.next"
               line("(void)#{codes[0]};")
               d = "#{hoist(recv, obj.ty)}.d"
               b = tmp
               line("#{c_type(args[1].ty)} *#{b} = #{codes[1]};")
               r = tmp
               s = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("int #{s} = #{helper('egg_dir')}_next(#{d}, &#{b}->ptr, &#{b}->len, &#{b}->cap);")
               line("#{r}.value = #{s} > 0;")
               line("if (#{s} < 0) #{r}.err = #{io_failed};")
               r
             when "DirReader.close"
               "#{helper('egg_dir')}_close(#{hoist(recv, obj.ty)}.d)"
             when "Reader.seek"
               f = file_of_value(recv, obj)
               r = tmp
               line("#{c_type(ret)} #{r} = { .err = 0 };")
               line("if (#{helper('egg_fs_seek')}(#{f}, #{codes[0]}) != 0) #{r}.err = #{io_failed};")
               r
             when "Allocator.create"
               # A copy of the value in the arena.
               t = args[0].ty
               ptr = tmp
               line("#{c_type(t)} *#{ptr} = (#{c_type(t)} *)#{helper('egg_alloc')}((int64_t)sizeof(#{c_type(t)}));")
               line("*#{ptr} = #{codes[0]};")
               ptr
             when "Allocator.alloc"
               # n copies of v in a new buffer
               elem = @types[ret].elem
               b = tmp
               line("#{c_type(ret)} #{b};")
               line("#{b}.len = #{codes[0]};")
               line("#{b}.ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(NULL, #{b}.len, sizeof(#{c_type(elem)}));")
               line("#{b}.cap = #{b}.len;")
               v = hoist(codes[1], elem)
               i = tmp
               line("for (int64_t #{i} = 0; #{i} < #{b}.len; #{i}++) #{b}.ptr[#{i}] = #{v};")
               b
             when "Allocator.free"
               t = args[0].ty
               info = @types[t]
               if !@checker.owned?(t)
                 "((void)#{codes[0]})" # a generic T that owns nothing
               elsif info.kind == :buf && !@checker.owned?(info.elem)
                 "free(#{codes[0]}.ptr)"
               else
                 "#{drop(t)}(#{codes[0]})"
               end
             when "Allocator.resize"
               # new elements, if it grows, are copies of v
               buf = args[0].ty
               elem = @types[buf].elem
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               n = hoist(codes[1], "i64")
               v = hoist(coerce(codes[2], args[2].ty, elem), elem)
               if @checker.owned?(elem)
                 # Elements cut off when it shrinks are freed first.
                 i = tmp
                 line("if (#{n} >= 0) for (int64_t #{i} = #{n}; #{i} < #{p}->len; #{i}++) #{drop(elem)}(#{p}->ptr[#{i}]);")
               end
               line("#{p}->ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(#{p}->ptr, #{n}, sizeof(#{c_type(elem)}));")
               line("#{p}->cap = #{n};")
               i = tmp
               line("for (int64_t #{i} = #{p}->len; #{i} < #{n}; #{i}++) #{p}->ptr[#{i}] = #{v};")
               line("#{p}->len = #{n};")
               "((void)0)"
             when "Allocator.push"
               # moved in at the end, one more element
               buf = args[0].ty
               elem = @types[buf].elem
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               v = hoist(coerce(codes[1], args[1].ty, elem), elem)
               # Out of room: double the capacity (at least 4), so pushes
               # cost amortized O(1).
               line("if (#{p}->len == #{p}->cap) {")
               line("    #{p}->cap = #{p}->cap < 2 ? 4 : #{helper('egg_mul')}(#{p}->cap, 2);")
               line("    #{p}->ptr = (#{c_type(elem)} *)#{helper('egg_buf_resize')}(#{p}->ptr, #{p}->cap, sizeof(#{c_type(elem)}));")
               line("}")
               line("#{p}->ptr[#{p}->len] = #{v};")
               line("#{p}->len++;")
               "((void)0)"
             when "Allocator.pop"
               # the last element moved out, or null; the memory stays
               buf = args[0].ty
               p = tmp
               line("#{c_type(buf)} *#{p} = #{codes[0]};")
               r = tmp
               line("#{c_type(ret)} #{r} = { .has = false };")
               line("if (#{p}->len > 0) { #{p}->len--; #{r}.value = #{p}->ptr[#{p}->len]; #{r}.has = true; }")
               r
             when "Allocator.leak"
               # A copy that lives as long as the program, even after a
               # Buf(u8) it came from is freed.
               "#{helper('egg_concat')}(#{coerce(codes[0], args[0].ty, 'str')}, ((egg_str){ \"\", 0 }))"
             when "Allocator.concat"
               r = tmp
               line("#{c_type(ret)} #{r} = #{empty_buf(ret)};")
               codes.each_index do |i|
                 v = hoist(coerce(codes[i], args[i].ty, "str"), "str")
                 line("#{helper('egg_append')}(&#{r}.ptr, &#{r}.len, &#{r}.cap, (const uint8_t *)#{v}.ptr, #{v}.len);")
               end
               r
             when "Allocator.append_str", "Allocator.append_int", "Allocator.append_float"
               # The buffer's three fields, then the text, an integer or a float.
               p = tmp
               line("#{c_type(args[0].ty)} *#{p} = #{codes[0]};")
               fields = "&#{p}->ptr, &#{p}->len, &#{p}->cap"
               t = args[1].ty
               case m
               when "Allocator.append_str"
                 s = coerce(codes[1], t, "str")
                 v = hoist(s, "str")
                 "#{helper('egg_append')}(#{fields}, (const uint8_t *)#{v}.ptr, #{v}.len)"
               when "Allocator.append_int"
                 if t.start_with?("i")
                   "#{helper('egg_append_int')}(#{fields}, (int64_t)#{codes[1]})"
                 else
                   "#{helper('egg_append_uint')}(#{fields}, (uint64_t)#{codes[1]})"
                 end
               else
                 "#{helper('egg_append_float')}(#{fields}, (double)#{codes[1]}, #{t == 'f32'})"
               end
             when "Allocator.int_str", "Allocator.float_str", "Allocator.str_from_c"
               r = tmp
               line("#{c_type(ret)} #{r} = #{empty_buf(ret)};")
               fields = "&#{r}.ptr, &#{r}.len, &#{r}.cap"
               t = args[0].ty
               case m
               when "Allocator.float_str" then line("#{helper('egg_append_float')}(#{fields}, (double)#{codes[0]}, #{t == 'f32'});")
               when "Allocator.str_from_c" then line("#{helper('egg_append_cstr')}(#{fields}, #{codes[0]});")
               else
                 fn, cast = t.start_with?("i") ? ["egg_append_int", "int64_t"] : ["egg_append_uint", "uint64_t"]
                 line("#{helper(fn)}(#{fields}, (#{cast})#{codes[0]});")
               end
               r
             when "Allocator.cstr" then "#{helper('egg_cstr')}(#{codes[0]})"
             else raise "codegen: unknown capability method #{m}"
             end
      text = "((void)#{recv}, #{text})"
      return text if ret == "void"
      hoist(text, ret)
    end

    def builtin(e, name, args)
      a = args[0]
      case name
      when "ptrAdd" then "(#{expr(a)} + #{expr(args[1])})"
      when "ptrCast" then "((#{c_type(e.ty)})(void *)#{expr(args[1])})"
      when "strPtr" then "((uint8_t *)#{expr(a)}.ptr)"
      when "bufPtr" then "(#{expr(a)}.ptr)"
      when "sliceFromPtr"
        p = hoist(expr(a), a.ty)
        n = hoist(expr(args[1]), "i64")
        line("#{helper('egg_slice_check')}(0, #{n}, #{n});")
        "((#{c_type(e.ty)}){ #{p}, #{n} })"
      when "intFromPtr" then "((size_t)(uintptr_t)#{expr(a)})"
      when "ptrFromInt" then "((#{c_type(e.ty)})(uintptr_t)#{expr(args[1])})"
      when "as"
        x = args[1]
        code = expr(x)
        return code if x.ty == e.ty
        return float_conv(x.ty, e.ty, code) if FLOAT_C.key?(x.ty) || FLOAT_C.key?(e.ty)
        as_conv(x.ty, e.ty, code)
      when "len"
        code = expr(a)
        len = e.info[:len]
        len.nil? ? "#{code}.len" : "((void)#{code}, INT64_C(#{len}))"
      when "sizeOf"
        "((int64_t)sizeof(#{c_type(e.info[:type])}))"
      when "typeName"
        name = e.info[:type]
        @need_str = true
        "((egg_str){ #{c_string(name)}, #{name.bytesize} })"
      when "forget" then "((void)#{expr(a)})"
      when "errorName"
        @need_str = true
        @need_error_names = true
        "egg_error_strs[#{expr(a)}]"
      when "replace", "take"
        # The place first, left to right; the value cannot change it (E117).
        t = e.ty
        p = tmp
        line("#{c_type(t)} *#{p} = &#{lvalue(a.expr)};")
        v = name == "take" ? empty_buf(t) : hoist(coerce(expr(args[1]), args[1].ty, t), t)
        old = tmp
        line("#{c_type(t)} #{old} = *#{p};")
        line("*#{p} = #{v};")
        old
      when "swap"
        # Left to right, and the container only once: its place may hold a
        # call. An index cannot change it (E117).
        obj = a.expr
        array = @types[obj.ty].kind == :array
        c = tmp
        line("#{c_type(obj.ty)} *#{c} = &#{lvalue(obj)};")
        i = hoist(expr(args[1]), "i64")
        j = hoist(expr(args[2]), "i64")
        t = @types[obj.ty].elem
        data = array ? "#{c}->a" : "((#{c_type(t)} *)#{c}->ptr)"
        len = array ? "INT64_C(#{@types[obj.ty].len})" : "#{c}->len"
        p = tmp
        q = tmp
        old = tmp
        line("#{c_type(t)} *#{p} = &#{data}[#{helper('egg_index')}(#{i}, #{len})];")
        line("#{c_type(t)} *#{q} = &#{data}[#{helper('egg_index')}(#{j}, #{len})];")
        line("#{c_type(t)} #{old} = *#{p};")
        line("*#{p} = *#{q};")
        line("*#{q} = #{old};")
        "((void)0)"
      when "splat"
        info = @types[e.ty]
        v = hoist(expr(a), info.elem)
        out = tmp
        i = tmp
        line("#{c_type(e.ty)} #{out};")
        line("for (int64_t #{i} = 0; #{i} < #{info.len}; #{i}++) #{out}.a[#{i}] = #{v};")
        out
      end
    end

    # A struct value to read a field from: places are read in place,
    # other expressions (calls) are already hoisted temporaries.
    def struct_value(obj)
      place?(obj) ? lvalue(obj) : expr(obj)
    end

    def index_expr(obj, index, len)
      t = obj.ty
      base = place?(obj) ? lvalue(obj) : expr(obj)
      i = expr(index)
      if t == "str"
        s = place?(obj) ? base : base
        return "((uint8_t)#{s}.ptr[#{helper('egg_index')}(#{i}, #{s}.len)])"
      end
      if %i[slice buf].include?(@types[t].kind)
        return "#{base}.ptr[#{helper('egg_index')}(#{i}, #{base}.len)]"
      end
      "#{base}.a[#{helper('egg_index')}(#{i}, INT64_C(#{len}))]"
    end

    def slice_expr(e)
      obj = e.obj
      t = obj.ty
      base = place?(obj) ? lvalue(obj) : hoist(expr(obj), t)
      lo = hoist(expr(e.lo), "i64")
      info = @types[t]
      len = if t == "str" || %i[slice buf].include?(info.kind) then "#{base}.len" else "INT64_C(#{info.len})" end
      hi = e.hi.nil? ? hoist(len, "i64") : hoist(expr(e.hi), "i64")
      line("#{helper('egg_slice_check')}(#{lo}, #{hi}, #{len});")
      # An empty buffer's ptr is NULL, and NULL + 0 is undefined in C; lo
      # > 0 means the length is too, so ptr is then not NULL.
      if t == "str"
        "((egg_str){ #{lo} ? #{base}.ptr + #{lo} : #{base}.ptr, #{hi} - #{lo} })"
      elsif %i[slice buf].include?(info.kind)
        "((#{c_type(e.ty)}){ #{lo} ? #{base}.ptr + #{lo} : #{base}.ptr, #{hi} - #{lo} })"
      else
        "((#{c_type(e.ty)}){ #{base}.a + #{lo}, #{hi} - #{lo} })"
      end
    end

    # All the values of one print; only the last ends the line.
    def locked_print(args, codes, f)
      line("EGG_LOCK(#{f});")
      codes.each_index { |i| line("#{print_one(args[i].ty, codes[i], i == args.length - 1, f)};") }
      line("EGG_UNLOCK(#{f});")
      "((void)0)"
    end

    # One value of io.print (or eprint), ending the line if nl.
    def print_one(t, code, nl, f = "stdout")
      case t
      when "bool" then "#{helper('egg_print_bool')}(#{f}, #{code}, #{nl})"
      when "str" then "#{helper('egg_print_str')}(#{f}, #{code}, #{nl})"
      when "Addr" then "#{helper('egg_print_addr')}(#{f}, #{code}, #{nl})"
      when ->(x) { text_type?(x) } then "#{helper('egg_print_str')}(#{f}, #{coerce(code, t, 'str')}, #{nl})"
      when "i64" then "#{helper('egg_print_i64')}(#{f}, #{code}, #{nl})"
      when "i8", "i16", "i32" then "#{helper('egg_print_i64')}(#{f}, (int64_t)#{code}, #{nl})"
      when "u8", "u16", "u32", "u64", "usize" then "#{helper('egg_print_u64')}(#{f}, (uint64_t)#{code}, #{nl})"
      when "f32", "f64" then "#{helper('egg_print_float')}(#{f}, (double)#{code}, #{t == 'f32'}, #{nl})"
      else
        @enum_names[t] = true
        "#{helper('egg_print_cstr')}(#{f}, #{@types[t].c_name}_names[#{code}], #{nl})"
      end
    end

    # Is e a place (variable, field of a place, element of a place)?
    def place?(e)
      case e
      in Var[info:] then !info.nil? && info[:local] == true
      in Deref then true
      in Field[obj:, info:] then (info.nil? || (info[:enum_index].nil? && info[:union_tag].nil?)) && place?(obj)
      in Index[obj:] then place?(obj) && obj.ty != "str" && @types[obj.ty]&.kind == :array
      else false
      end
    end

    def lvalue(e)
      case e
      in Var[name:] then var_ref(name)
      in Deref[expr: ptr]
        # Checked: a null pointer panics instead of crashing.
        p = place?(ptr) ? lvalue(ptr) : hoist(expr(ptr), ptr.ty)
        "(*(#{p} != NULL ? #{p} : (#{c_type(ptr.ty)})#{helper('egg_null_deref')}()))"
      in Field[obj:, name:] then "#{lvalue(obj)}.f_#{name}"
      in Index[obj:, index:, info:]
        if @types[obj.ty]&.kind == :buf
          b = lvalue(obj)
          "#{b}.ptr[#{helper('egg_index')}(#{expr(index)}, #{b}.len)]"
        elsif @types[obj.ty]&.kind == :slice
          # Only an inout slice is written: it views a mutable place.
          b = lvalue(obj)
          "((#{c_type(e.ty)} *)#{b}.ptr)[#{helper('egg_index')}(#{expr(index)}, #{b}.len)]"
        else
          "#{lvalue(obj)}.a[#{helper('egg_index')}(#{expr(index)}, INT64_C(#{info[:len]}))]"
        end
      else raise "codegen: not a place: #{e.class}"
      end
    end

    def var_ref(name)
      _, inout = local(name)
      inout ? "(*v_#{name})" : "v_#{name}"
    end

    def local(name)
      i = @locals.length - 1
      while i >= 0
        t = @locals[i][name]
        return t unless t.nil?
        i -= 1
      end
      raise "codegen: unknown local #{name}"
    end
  end
